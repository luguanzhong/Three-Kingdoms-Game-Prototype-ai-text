# 【本模块的总原则】所有函数都是"确定性判定"：
#   输入一组明确的条件 → 经过纯算术比较 → 输出唯一确定的结果。
#   全模块不导入任何随机库、不调用任何随机函数，也没有隐藏的骰子。
#   军事行动只看"有效兵力"对比（有效兵力 = 兵力 × (1 + 精锐比例/100)），
#   计谋只看"前置条件是否达成"。
#
# 【关于需求3.3中百分比伤亡的说明】需求原文对"死守/默认驻守"给出了百分比结局，
#   与"严禁随机死亡"的总原则冲突。为保证全局零随机，本原型把百分比结局
#   "确定化"为固定结局（取各分支中最能保留"代价感"的一种），详见城破伤亡判定。

def 计算强攻判定(进攻兵力, 守军):
    """需求5.1：兵力 > 守军×1.5 → 强攻100%胜利（损失 = 守军×0.8）。
    纯数值比较，无随机。返回(是否必胜, 预计损失, 说明)。"""
    if 进攻兵力 > 守军 * 1.5:
        损失 = int(守军 * 0.8)
        return True, 损失, f"强攻必胜！但需付出惨重代价，预计损失兵力 {损失}。"
    return False, 0, f"强攻无必胜把握（需进攻兵力 > 守军×1.5 = {int(守军 * 1.5)}）。"


def 计算围攻判定(进攻兵力, 守军):
    """需求5.1：兵力 > 守军×0.8 → 围攻100%胜利（需消耗3回合粮草）。无随机。"""
    if 进攻兵力 > 守军 * 0.8:
        return True, f"围攻可行：围而不攻，3回合后敌军粮尽投降（需持续消耗3回合粮草）。"
    return False, f"围攻不可行（需进攻兵力 > 守军×0.8 = {int(守军 * 0.8)}）。"


def 计算必败判定(进攻兵力, 守军):
    """需求5.1：兵力 < 守军×0.5 → 此战必败，系统禁止送死（唯一例外：死士突袭）。"""
    if 进攻兵力 < 守军 * 0.5:
        return True, "此战必败！系统禁止无意义送死。唯一例外是【死士突袭】——那将必定牺牲将领或部队。"
    return False, "此战无必胜把握（兵力介于守军×0.5与×0.8之间），系统禁止盲目进攻。"


def 防御加成计算(将领):
    """确定性防御加成公式（需求3.2 + 5.2 + MVP补充）：
    镇守城池：统御×10%；驻守险关：统御×20%（防御效果翻倍）；
    死守+20%、提前撤退-10%（MVP补充，让守城指令存在战前权衡）；
    已据险而守：总加成再×2（山上扎营/据险而守，防御100%翻倍）。"""
    if 将领 is None or 将领["状态"] != "正常":
        return 0.0
    加成 = 0.0
    if 将领["任务"] == "镇守城池":
        加成 += 将领["统御"] * 0.10
    elif 将领["任务"] == "驻守险关":
        加成 += 将领["统御"] * 0.20
    if 将领["指令"] == "死守":
        加成 += 0.20
    elif 将领["指令"] == "提前撤退":
        加成 -= 0.10
    if 将领["据险"]:
        加成 *= 2.0
    return 加成


def 攻城结算(进攻兵力, 守军, 防守将领):
    """通用确定性城池攻防：
    守值 = 守军 × (1 + 防守将领防御加成)。
    进攻兵力 > 守值×1.5 → 城破（返回True）；否则击退（返回False）。零随机。"""
    守值 = int(守军 * (1 + 防御加成计算(防守将领)))
    if 进攻兵力 > 守值 * 1.5:
        return True, 守值
    return False, 守值


def 城破伤亡判定(将领, 指令):
    """需求3.3的确定性化：城破时将领结局100%由玩家预设指令决定，严禁随机。
    确定化规则（原百分比结局在注释中保留对照）：
      提前撤退 → 100%存活退回后方，但民心下降（由调用方扣除）。
      死守     → 统御≥8：重伤撤离（原型70%战死/30%重伤，取可保留的"重伤"结局）；
                  统御<8：战死（原型90%战死，确定化为100%）。
      默认驻守 → 被俘（原型50%被俘/30%战死/20%突围，取"被俘"，可用粮草赎回）。
    """
    if 指令 == "提前撤退":
        return f"{将领['姓名']}依令提前撤退，安然退回后方（100%存活，民心将下降）。"
    if 指令 == "死守":
        if 将领["统御"] >= 8:
            将领["状态"] = "重伤"
            将领["重伤剩余"] = 1
            return f"{将领['姓名']}死守孤城，身被数创，幸得亲兵拼死救出——重伤撤离，需休整1回合。"
        将领["状态"] = "已殁"
        return f"{将领['姓名']}死守不退，力战而亡！"
    # 默认驻守（未预设指令）→ 确定化为被俘
    将领["状态"] = "被俘"
    return f"{将领['姓名']}未得明确指令，城破被俘！可用粮草40在外交菜单赎回。"


def 死士突袭(目标, 领将):
    """需求5.1：必败之战唯一例外。突袭必定牺牲将领或部队，二选一，零随机。"""
