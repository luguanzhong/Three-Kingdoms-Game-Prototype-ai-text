def 计谋_据险而守(将领):
    """前置：①将领所在地为山地险关（汉中/阆中）②将领任务为驻守险关。
    条件满足 → 防御力100%翻倍（永久生效，直到任务变更）。零随机。"""
    if 将领["状态"] != "正常":
        return False, f"前置条件不满足：{将领['姓名']}当前无法执行任务。"
    if 将领["位置"] not in 险关位置:
        return False, f"前置条件不满足：{将领['位置']}无山地地形可据（险关：汉中、阆中）。"
    if 将领["任务"] != "驻守险关":
        return False, "前置条件不满足：需先将其任务设为【驻守险关】。"
    if 将领["据险"]:
        return False, "已据险而守，防御已是翻倍状态。"
    将领["据险"] = True
    return True, f"{将领['姓名']}于{将领['位置']}依山扎营、据险而守，防御力100%翻倍！"


def 计谋_劝降(城, 敌将, 使臣):
    """前置：①守将忠诚<5 ②使臣智谋≥8。条件满足 → 100%劝降成功，全城来归。零随机。
    曹魏诸将大多忠心耿耿（忠诚≥5），劝降必然失败；唯宛城侯音（忠诚4）可劝降。"""
