def 选择将领菜单(提示):
    """列出当前可行动（状态=正常）的将领并返回所选将领字典；返回None表示放弃。"""
    可行动 = [将 for 将 in 将领们 if 将["状态"] == "正常"]
    if not 可行动:
        print("当前没有可行动的将领。")
        return None
    for 序号, 将领 in enumerate(可行动, 1):
        print(f"{序号}. {将领['姓名']}（{将领['位置']}｜{将领['任务']}｜指令:{将领['指令']}）"
              f"统御{将领['统御']} 智谋{将领['智谋']} 内政{将领['内政']} 忠诚{将领['忠诚']}")
    print("0. 返回")
    输入 = input(提示).strip()
    if 输入 == "" or 输入 == "0":
        return None
    try:
        序号 = int(输入)
        if 1 <= 序号 <= len(可行动):
            return 可行动[序号 - 1]
    except ValueError:
        pass
    print("无效选择。")
    return None


