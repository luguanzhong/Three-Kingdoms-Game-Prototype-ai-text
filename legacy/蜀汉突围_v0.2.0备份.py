def 阈值事件检查():
    """需求6：数值触碰阈值 → 自动弹出事件。全部为确定触发、确定惩罚，无概率。
    同一事件在条件持续期间只触发一次（"触碰"语义），条件回落后可再次触发。"""
    # 魏国压力>80 → 魏军压境：兵力强制扣除20%
    if 蜀汉["魏国压力"] > 80 and not 全局["魏军压境已触发"]:
        全局["魏军压境已触发"] = True
        损失 = int(蜀汉["兵力"] * 0.2)
        蜀汉["兵力"] = max(0, 蜀汉["兵力"] - 损失)
        记录(f"【魏军压境】魏国压力>80！魏军大举来犯，兵力被强制扣除20%（-{损失}）。")
    elif 蜀汉["魏国压力"] <= 80:
        全局["魏军压境已触发"] = False

    # 粮草<20 且 东吴观望>70 → 东吴闭粮：粮草-10
    if 蜀汉["粮草"] < 20 and 东吴["观望态度"] > 70 and not 全局["东吴闭粮已触发"]:
        全局["东吴闭粮已触发"] = True
        蜀汉["粮草"] = max(0, 蜀汉["粮草"] - 10)
        记录("【东吴闭粮】粮草<20且东吴观望>70！东吴禁运，粮草-10。")
    elif not (蜀汉["粮草"] < 20 and 东吴["观望态度"] > 70):
        全局["东吴闭粮已触发"] = False

    # 兵力<5000 → 国势衰微：所有将领忠诚-2
    if 蜀汉["兵力"] < 5000 and not 全局["国势衰微已触发"]:
        全局["国势衰微已触发"] = True
        for 将领 in 将领们:
            if 将领["状态"] != "已殁":
                将领["忠诚"] = max(0, 将领["忠诚"] - 2)
        记录("【国势衰微】兵力<5000！人心浮动，所有将领忠诚-2。")
    elif 蜀汉["兵力"] >= 5000:
        全局["国势衰微已触发"] = False


def 结算回合():
    """需求4：每回合自动推演。全部为确定性计算，顺序固定。"""
    # 1. 曹魏增长：兵力+2%、粮草+10；扩张倾向影响魏国压力
    曹魏["兵力"] = int(曹魏["兵力"] * 1.02)
    曹魏["粮草"] += 10
    if 曹魏["扩张倾向"] > 70:
        蜀汉["魏国压力"] += 5
        记录("曹魏扩张倾向高涨，魏国压力+5。")
    elif 曹魏["扩张倾向"] < 50:
        蜀汉["魏国压力"] = max(0, 蜀汉["魏国压力"] - 2)
        记录("曹魏收缩防线，魏国压力-2。")

    # 2. 蜀汉粮草消耗（兵力÷1000向下取整）与粮荒判定
    消耗 = 蜀汉["兵力"] // 1000
    if any(将["状态"] == "正常" and 将["任务"] == "驻守险关" and 将["位置"] in 险关位置 for 将 in 将领们):
        消耗 = max(1, 消耗 // 2)      # 驻守险关：粮草消耗减半
    蜀汉["粮草"] = max(0, 蜀汉["粮草"] - 消耗)
    记录(f"大军日常消耗，本回合粮草-{消耗}。")   # 新增：日常消耗计入近事
    if 蜀汉["粮草"] < 30:
        蜀汉["兵力"] = int(蜀汉["兵力"] * 0.95)
        记录(f"粮荒！粮草仅余{蜀汉['粮草']}，兵无粮自溃，兵力减损5%。")

    # 3. 将领任务结算（需求3.2）
    for 将领 in 将领们:
        if 将领["状态"] != "正常":
            continue
        if 将领["任务"] == "后方屯田":
            收入 = int(将领["内政"] * 2 * 蜀汉["民心"] / 100)   # 民心影响粮草征收
            蜀汉["粮草"] += 收入
            if 收入 > 0:
                记录(f"{将领['姓名']}屯田，粮草+{收入}。")
        elif 将领["任务"] == "练兵":
            增长 = 将领["统御"] * 5
            蜀汉["兵力"] += 增长
            记录(f"{将领['姓名']}练兵，兵力+{增长}。")
        elif 将领["任务"] == "外交使节":
            增长 = 将领["智谋"] * 2
            蜀汉["东吴好感"] = min(100, 蜀汉["东吴好感"] + 增长)
            记录(f"{将领['姓名']}出使东吴，东吴好感+{增长}。")
        elif 将领["任务"] == "镇守城池":
            # 新增子任务系统（仅镇守城池时生效）
            if 将领["子任务"] == "练兵":
                蜀汉["精锐比例"] = min(100, 蜀汉["精锐比例"] + 5)
                记录(f"{将领['姓名']}练兵，精锐比例+5。")
            elif 将领["子任务"] == "募兵":
                蜀汉["兵力"] += 200
                蜀汉["粮草"] = max(0, 蜀汉["粮草"] - 20)
                记录(f"{将领['姓名']}募兵，兵力+200，粮草-20。")

    # 4. 东吴骑墙（需求4）
    if 蜀汉["魏国压力"] > 70:
        东吴["观望态度"] += 3
        记录("魏国压力高企，东吴坐山观虎斗（观望+3）。")
    elif 蜀汉["魏国压力"] < 30:
        东吴["观望态度"] = max(0, 东吴["观望态度"] - 2)
        记录("蜀汉压力缓和，东吴观望-2。")

    # 5. 田忌赛马规则：前线必须有统御≥8的名将，否则压力急剧上升
    if not any(将["状态"] == "正常" and 将["统御"] >= 8 and 将["任务"] in ("镇守城池", "驻守险关", "北伐先锋") for 将 in 将领们):
        蜀汉["魏国压力"] += 8
        记录("前线无名将坐镇，魏国压力+8（田忌赛马：名将不可尽藏于后）。")

    # 6. 围攻推进（需求5.1：围攻消耗3回合粮草）
    if 全局["围攻状态"] is not None:
        围攻 = 全局["围攻状态"]
        围攻["剩余"] -= 1
        额外粮草 = 围攻["出征兵力"] // 1000
        蜀汉["粮草"] = max(0, 蜀汉["粮草"] - 额外粮草)
        if 围攻["剩余"] <= 0:
            领将 = 按姓名查找(围攻["领将"])
            记录(f"围攻{围攻['目标']}三旬，城中粮尽。")
            攻占城池(围攻["目标"], 领将, 0.3, "围攻")
            全局["围攻状态"] = None
        else:
            记录(f"围攻{围攻['目标']}中（尚需{围攻['剩余']}回合，本回合额外耗粮{额外粮草}）。")

    # 7. 曹魏主动进攻（v0.2.0：洛阳陷落后中枢崩溃，曹魏不再进攻）
    if 曹魏["扩张倾向"] > 70 and 蜀汉["魏国压力"] > 50 and 敌方城池["洛阳"]["归属"] != "蜀汉":
        曹魏进攻结算()

    # 8. 东吴背刺（观望>80）
    if 东吴["观望态度"] > 80:
        东吴背刺结算()

    # 9. 重伤恢复（1回合后归队）
    for 将领 in 将领们:
        if 将领["状态"] == "重伤":
            将领["重伤剩余"] -= 1
            if 将领["重伤剩余"] <= 0:
                将领["状态"] = "正常"
                记录(f"{将领['姓名']}伤愈归队。")

    # 10. 民心自然恢复（MVP补充：每回合+3，上限100）
    蜀汉["民心"] = min(100, 蜀汉["民心"] + 3)

    # 11. 连锁事件计时：占领曹魏城池3回合后，曹魏邻线增兵（需求5.3）
    if 全局["连锁计时"] > 0:
        全局["连锁计时"] -= 1
        if 全局["连锁计时"] == 0:
            蜀汉["魏国压力"] += 20
            曹魏["扩张倾向"] += 15
            记录("连锁事件：曹魏在邻线增兵报复！魏国压力+20、扩张倾向+15，边境告急！")

    # 12. 阈值事件（需求6）
    阈值事件检查()


def 结局判定():
    """需求7：结局判定。零随机，只看硬条件。v0.2.0：新增北伐大捷分支（最优先）。"""
    if 敌方城池["洛阳"]["归属"] == "蜀汉":
        return "【结局】北伐大捷！汉家旗帜插上洛阳城头，光复汉室，在此一举！"
    if 蜀汉["兵力"] <= 0:
        return "【结局】星落秋风，蜀汉重蹈覆辙"
    if 蜀汉["魏国压力"] > 100:
        return "【结局】星落秋风，蜀汉重蹈覆辙"
