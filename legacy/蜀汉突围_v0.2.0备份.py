def 填充(文本, 宽度):
    """按显示宽度填充空格：中文等宽字符算2列，保证表格对齐（纯标准库实现）。"""
    实宽 = sum(2 if ord(字) > 127 else 1 for 字 in 文本)
    return 文本 + " " * max(0, 宽度 - 实宽)


