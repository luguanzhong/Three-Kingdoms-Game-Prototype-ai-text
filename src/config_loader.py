class 配置错误(Exception):
    """配置非法异常（严格模式下抛出，消息已包含文件、字段、期望值、实际值与修复提示）。"""


def 深拷贝(对象):
    """递归拷贝 dict / list（只用标准库，避免引入 copy 之外的行为差异）。"""
    if isinstance(对象, dict):
        return {键: 深拷贝(值) for 键, 值 in 对象.items()}
    if isinstance(对象, list):
        return [深拷贝(元素) for 元素 in 对象]
    return 对象


def 内置默认配置():
    """返回内置默认配置的深拷贝（调用方可安全修改）。"""
    return 深拷贝(内置默认)


def 深合并(基础, 覆盖):
    """把 覆盖 合并进 基础（只覆盖同名叶子，缺失字段保留默认）。"""
    for 键, 值 in 覆盖.items():
        if isinstance(值, dict) and isinstance(基础.get(键), dict):
            深合并(基础[键], 值)
        else:
            基础[键] = 值
    return 基础


def 取路径(字典, 路径):
    """按 "a.b.c" 取嵌套值，缺失时返回 None。"""
    当前 = 字典
    for 段 in 路径.split("."):
        if not isinstance(当前, dict) or 段 not in 当前:
            return None
        当前 = 当前[段]
    return 当前


def 类型名(值):
    """给出中文类型名，用于错误文案。"""
    if isinstance(值, bool):
        return "布尔值"
    if isinstance(值, int):
        return "整数"
    if isinstance(值, float):
        return "小数"
    if isinstance(值, str):
        return "字符串"
    if isinstance(值, list):
        return "列表"
    if isinstance(值, dict):
        return "字典"
    return type(值).__name__


# 允许类型的中文名（用于把校验报错写成"期望 0~100 之间的整数"这样的人话）
数值类型中文 = {int: "整数", float: "小数"}


def 数值期望描述(允许类型, 最小值, 最大值):
    """把「允许类型 + 数值范围」描述成可读文本，例如 `0~100 之间的整数`。

    注意：这里必须按 *允许类型本身* 取名，而不能用 类型名(允许类型[0])——
    后者算的是 `type(int).__name__`，会得到 "type" 这种漏出英文的文案。
    """
    if len(允许类型) == 1:
        名称 = 数值类型中文.get(允许类型[0], 允许类型[0].__name__)
    else:
        名称 = "整数或小数"
    return f"{最小值}~{最大值} 之间的{名称}"


def 路径所属文件(路径):
    """把配置路径（如 战斗.强攻.损失系数）映射回来源文件名。"""
    顶层键 = 路径.split(".")[0]
    for 文件名, 键名 in 配置文件名映射.items():
        if 键名 == 顶层键:
            return "config/" + 文件名
    return "config/（未知文件）"


def 展开叶子路径(字典, 前缀=""):
    """展开配置的所有叶子路径；特殊子树整体返回，不再向下展开。"""
    结果 = []
    for 键, 值 in 字典.items():
        路径 = (前缀 + "." + 键) if 前缀 else 键
        if 路径 in 特殊子树:
            结果.append(路径)
        elif isinstance(值, dict):
            结果.extend(展开叶子路径(值, 路径))
        else:
            结果.append(路径)
    return 结果


def 校验(配置):
    """校验合并后的配置，返回错误信息列表（为空表示全部合法）。"""
    错误 = []

    # 1）数值字段：类型（拒绝布尔）、范围
    for 路径, (允许类型, 最小值, 最大值) in 数值规则.items():
        值 = 取路径(配置, 路径)
        if 值 is None:
            错误.append(f"{路径所属文件(路径)} → 字段 \"{路径}\"：缺少该字段"
                        f"（应为 {数值期望描述(允许类型, 最小值, 最大值)}）")
            continue
        if isinstance(值, bool) or not isinstance(值, 允许类型):
            错误.append(f"{路径所属文件(路径)} → 字段 \"{路径}\"："
                        f"期望 {数值期望描述(允许类型, 最小值, 最大值)}，"
                        f"实际 {值!r}（{类型名(值)}）")
            continue
        if 值 < 最小值 or 值 > 最大值:
            错误.append(f"{路径所属文件(路径)} → 字段 \"{路径}\"：数值超出范围，"
                        f"期望 {数值期望描述(允许类型, 最小值, 最大值)}，实际 {值}")

    # 2）字符串字段：枚举合法 / 交叉引用存在
    情报键名 = 取路径(配置, "计谋.情报键名")
    for 路径, 允许 in 字符串规则.items():
        值 = 取路径(配置, 路径)
        if 值 is None:
            错误.append(f"{路径所属文件(路径)} → 字段 \"{路径}\"：缺少该字段")
            continue
        if not isinstance(值, str):
            错误.append(f"{路径所属文件(路径)} → 字段 \"{路径}\"：期望字符串，实际 {值!r}（{类型名(值)}）")
            continue
        if 允许 == "情报键名":
            if not isinstance(情报键名, list) or 值 not in 情报键名:
                错误.append(f"{路径所属文件(路径)} → 字段 \"{路径}\"：引用了不存在的情报键名 {值!r}，"
                             f"可选值来自 计谋.情报键名 = {情报键名!r}")
        elif 值 not in 允许:
            错误.append(f"{路径所属文件(路径)} → 字段 \"{路径}\"：期望以下之一 {允许!r}，实际 {值!r}")

    # 3）列表字段：元素类型与长度
    for 路径, (元素类型, 最少, 最多) in 列表规则.items():
        值 = 取路径(配置, 路径)
        if 值 is None:
            错误.append(f"{路径所属文件(路径)} → 字段 \"{路径}\"：缺少该字段（应为列表）")
            continue
        if not isinstance(值, list):
            错误.append(f"{路径所属文件(路径)} → 字段 \"{路径}\"：期望列表，实际 {值!r}（{类型名(值)}）")
            continue
        if not (最少 <= len(值) <= 最多):
            错误.append(f"{路径所属文件(路径)} → 字段 \"{路径}\"：列表长度应在 {最少}~{最多}，实际 {len(值)}")
        for 序号, 元素 in enumerate(值, 1):
            if not isinstance(元素, 元素类型) or isinstance(元素, bool):
                错误.append(f"{路径所属文件(路径)} → 字段 \"{路径}\" 第 {序号} 项："
                             f"期望{类型名(元素类型)}，实际 {元素!r}（{类型名(元素)}）")

    # 4）季节月份：季节名必须是代码判定的四个季节，且不重不漏覆盖 1~12 月
    季节月份 = 取路径(配置, "季节.季节月份")
    if not isinstance(季节月份, dict):
        错误.append("config/seasons.json → 字段 \"季节月份\"：期望字典，"
                     f"实际 {季节月份!r}（{类型名(季节月份)}）")
    else:
        for 季节名 in 季节月份:
            if 季节名 not in 必须季节名:
                错误.append(f"config/seasons.json → 字段 \"季节月份.{季节名}\"：未知季节名，"
                             f"只能是 {list(必须季节名)!r}")
        for 名称 in 必须季节名:
            if 名称 not in 季节月份:
                错误.append(f"config/seasons.json → 字段 \"季节月份\"：缺少季节 {名称!r}（代码依赖该名称判定）")
        已用月份 = []
        for 季节名, 月份列表 in 季节月份.items():
            if not isinstance(月份列表, list):
                错误.append(f"config/seasons.json → 字段 \"季节月份.{季节名}\"：期望月份列表，"
                             f"实际 {月份列表!r}（{类型名(月份列表)}）")
                continue
            for 月 in 月份列表:
                if not isinstance(月, int) or isinstance(月, bool) or not (1 <= 月 <= 12):
                    错误.append(f"config/seasons.json → 字段 \"季节月份.{季节名}\"：月份必须是 1~12 的整数，"
                                 f"实际 {月!r}（{类型名(月)}）")
                    continue
                已用月份.append(月)
        重复 = sorted({月 for 月 in 已用月份 if 已用月份.count(月) > 1})
        if 重复:
            错误.append(f"config/seasons.json → 字段 \"季节月份\"：月份被多个季节重复占用 {重复}")
        缺失 = sorted(set(range(1, 13)) - set(已用月份))
        if 缺失:
            错误.append(f"config/seasons.json → 字段 \"季节月份\"：以下月份未被任何季节覆盖 {缺失}")

    # 5）顺序一致性（数值关系必须成立，否则判定分支会互相矛盾）
    强攻倍率 = 取路径(配置, "战斗.强攻.兵力倍率下限")
    围攻倍率 = 取路径(配置, "战斗.围攻.兵力倍率下限")
    必败倍率 = 取路径(配置, "战斗.必败.兵力倍率上限")
    if all(isinstance(值, (int, float)) and not isinstance(值, bool)
           for 值 in (强攻倍率, 围攻倍率, 必败倍率)):
        if not (必败倍率 < 围攻倍率 < 强攻倍率):
            错误.append("config/battle.json → 字段 \"强攻/围攻/必败 兵力倍率\"：必须满足 "
                         f"必败上限({必败倍率}) < 围攻下限({围攻倍率}) < 强攻下限({强攻倍率})")
    密使阈 = 取路径(配置, "外交.亲魏.密使观望阈值")
    盟约阈 = 取路径(配置, "外交.亲魏.盟约观望阈值")
    if isinstance(密使阈, int) and isinstance(盟约阈, int) and not (密使阈 < 盟约阈):
        错误.append("config/diplomacy.json → 字段 \"亲魏.密使观望阈值/盟约观望阈值\"：必须满足 "
                     f"密使阈值({密使阈}) < 盟约阈值({盟约阈})")
    亲蜀上限 = 取路径(配置, "外交.势力比阈值.亲蜀上限")
    亲魏下限 = 取路径(配置, "外交.势力比阈值.亲魏下限")
    if all(isinstance(值, (int, float)) and not isinstance(值, bool) for 值 in (亲蜀上限, 亲魏下限)):
        if not (亲蜀上限 < 亲魏下限):
            错误.append("config/diplomacy.json → 字段 \"势力比阈值\"：必须满足 "
                         f"亲蜀上限({亲蜀上限}) < 亲魏下限({亲魏下限})")
    比例上限 = 取路径(配置, "兵种.精锐.比例上限")
    练兵加成 = 取路径(配置, "兵种.精锐.每回合练兵加成")
    if isinstance(比例上限, int) and isinstance(练兵加成, int) and 练兵加成 > 比例上限:
        错误.append("config/units.json → 字段 \"精锐.比例上限/每回合练兵加成\"：练兵加成不得大于比例上限 "
                     f"（上限 {比例上限}，加成 {练兵加成}）")

    return 错误


def 校验未知字段(已加载):
    """检查用户在配置文件里写了但代码不认识的字段（多为拼写错误）。"""
    错误 = []
    已知 = set(数值规则) | set(字符串规则) | set(列表规则) | set(特殊子树)
    for 文件名, 顶层键 in 配置文件名映射.items():
        内容 = 已加载.get(文件名)
        if not isinstance(内容, dict):
            continue
        for 路径 in 展开叶子路径(内容, 顶层键):
            if 路径 not in 已知:
                错误.append(f"config/{文件名} → 字段 \"{路径[len(顶层键) + 1:]}\"：未知字段"
                             f"（可能是拼写错误，请对照 README「配置说明」）")
    return 错误


def 载入配置(配置目录=None, 严格=False):
    """读取并校验配置。

    参数：
      配置目录：默认为项目根目录下的 config/（与启动时的工作目录无关）。
      严格：True 时任何问题都抛出 配置错误；False 时打印/记录错误并回退内置默认值。

    返回：合并校验后的配置字典（严格模式失败会抛异常，不会返回）。
    """
    global 最后错误信息
    if 配置目录 is None:
        配置目录 = os.path.join(项目根目录, "config")

    配置 = 内置默认配置()
    错误 = []
    已加载 = {}

    if not os.path.isdir(配置目录):
        错误.append(f"{配置目录} → 配置目录不存在（已回退内置默认配置）")
    else:
        for 文件名, 顶层键 in 配置文件名映射.items():
            路径 = os.path.join(配置目录, 文件名)
            if not os.path.isfile(路径):
                错误.append(f"config/{文件名} → 文件缺失（该文件对应的 \"{顶层键}\" 项将使用内置默认值）")
                continue
            try:
                with open(路径, "r", encoding="utf-8") as 文件:
                    内容 = json.load(文件)
            except json.JSONDecodeError as 异常:
                错误.append(f"config/{文件名} → JSON 语法错误：第 {异常.lineno} 行第 {异常.colno} 列，"
                             f"{异常.msg}（已回退内置默认值）")
                continue
            except OSError as 异常:
                错误.append(f"config/{文件名} → 文件无法读取：{异常}")
                continue
            if not isinstance(内容, dict):
                错误.append(f"config/{文件名} → 顶层必须是 JSON 对象，实际 {类型名(内容)}")
                continue
            已加载[文件名] = 内容
            深合并(配置, {顶层键: 内容})

    错误.extend(校验(配置))
    错误.extend(校验未知字段(已加载))

    if 错误:
        文本 = "\n".join("  · " + 一条 for 一条 in 错误)
        最后错误信息 = f"检测到 {len(错误)} 处配置问题：\n{文本}\n  提示：修改 config/ 下对应文件后重新运行；" \
                       f"或执行 python config_loader.py 单独校验；删除 config/ 可回退内置默认值。"
        日志.warning("配置存在 %d 处问题，将回退内置默认值；首个问题：%s", len(错误), 错误[0])
        if 严格:
            raise 配置错误(最后错误信息)
        配置 = 内置默认配置()      # 非严格模式：整体回退，确保非法值绝不进入游戏逻辑
    else:
        最后错误信息 = ""
        日志.info("配置加载完成：目录 %s ｜ 数值项 %d / 字符串项 %d / 列表项 %d",
                 配置目录, len(数值规则), len(字符串规则), len(列表规则))

    return 配置


if __name__ == "__main__":
    载入配置(严格=False)
    if 最后错误信息:
        print("[配置校验] 未通过")
        raise SystemExit(1)
    print("[配置校验] 通过：config/ 下 5 个配置文件合法，且与内置默认值一致地可用于游戏。")
