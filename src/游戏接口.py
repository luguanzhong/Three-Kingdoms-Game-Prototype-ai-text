class 会话:
    """一局游戏的会话：持有引擎模块实例，负责驱动它、并向界面暴露状态。"""

    def __init__(self):
        self.游戏 = None
        self.输出回调 = None
        self.询问回调 = None
        self.结局 = None
        self.大事已用 = False
        self.载入的槽位 = None

    # ═══════════════════════════════════════════════════════════
    #  一、开局
    # ═══════════════════════════════════════════════════════════
    def 新开局(self, 输出回调, 询问回调):
        """开一局新游戏：重新执行引擎模块，回到初始状态（208 年 9 月）。

        注意：**每次都要 reload**，不能只在"首次"导入。因为 `importlib.import_module`
        对已在 sys.modules 里的模块会直接返回旧对象——那是一个带着上一局残留状态的引擎，
        会导致"新开局"其实不是新局（同一个进程里开第二局、或连续两次 new 会话时都会踩到）。
        """
        self.输出回调 = 输出回调
        self.询问回调 = 询问回调
        self.结局 = None
        self.大事已用 = False
        self.载入的槽位 = None
        if self.游戏 is None:
            self.游戏 = importlib.import_module("蜀汉突围")
        # 重执行模块源码 → 所有模块级字面量回到初始值，等价于"重开一局"
        self.游戏 = importlib.reload(self.游戏)
        self._接管输入输出()
        self.输出("════════════════════════════════════════════")
        self.输出("  三国 · 蜀汉突围 —— 图形界面版")
        self.输出("  你是诸葛亮举荐的幕僚。计谋无概率，将领无天命。")
        self.输出("════════════════════════════════════════════")
        if getattr(self.游戏, "配置警告", None):
            self.输出("【配置警告】" + self.游戏.配置警告)
        self._执行(打印局势=False)   # 触发一次引擎自身的局势打印，让战报区有开局画面
        return True, "新开局已就绪"

    def 读档开局(self, 槽位, 输出回调, 询问回调):
        """从槽位继续一局：先按新开局初始化引擎，再把存档状态覆盖回去。"""
        成功, 提示 = self.新开局(输出回调, 询问回调)
        成功, 提示 = self.保存读档(槽位)
        if 成功:
            self.载入的槽位 = 槽位
            self.输出(f"（已从{槽位显示名.get(槽位, 槽位)}继续）")
        return 成功, 提示

    # ═══════════════════════════════════════════════════════════
    #  二、驱动引擎（输入/输出接管）
    # ═══════════════════════════════════════════════════════════
    def _接管输入输出(self):
        """把引擎的 input 换成界面询问回调；界面未提供回调时返回"0"（等价于放弃），绝不卡死。"""
        会话自身 = self

        def 界面输入(提示=""):
            回调 = 会话自身.询问回调          # 动态读取：界面可以在运行中更换回调
            if 回调 is None:
                return "0"
            答案 = 回调(提示)
            return "0" if 答案 is None else str(答案)

        self.游戏.input = 界面输入

    def 输出(self, 文本):
        if self.输出回调 is not None and 文本 != "":
            self.输出回调(文本)

    def 执行引擎函数(self, 函数名, *参数):
        """调用引擎函数，并把它的 print 输出实时送进界面的战报区。

        返回引擎函数的返回值（若它没有返回值则返回 None）。
        注意：**不做任何规则判断**，一切交给引擎。
        """
        缓冲 = _输出转发器(self.输出)
        结果 = None
        with contextlib.redirect_stdout(缓冲):
            结果 = getattr(self.游戏, 函数名)(*参数)
        缓冲.冲刷()
        return 结果

    def _执行(self, 打印局势=True):
        """调用引擎自身的局势打印（界面战报区的内容来源之一）。"""
        self.执行引擎函数("打印局势")

    # ═══════════════════════════════════════════════════════════
    #  三、行动
    # ═══════════════════════════════════════════════════════════
    def 行动可用(self, 行动):
        """本回合该行动是否可用（大事名额是唯一的限制条件）。"""
        if self.结局:
            return False, "本局已结束"
        if 行动["大事"] and self.大事已用:
            return False, "本回合已执行过大事，请结束本回合"
        return True, ""

    def 执行行动(self, 行动键):
        """执行一个行动。返回 (是否成功, 提示)。成功且属于"大事"时会占用本回合名额。"""
        行动 = next((项 for 项 in 行动表 if 项["键"] == 行动键), None)
        if 行动 is None:
            return False, f"未知行动：{行动键}"
        可用, 原因 = self.行动可用(行动)
        if not 可用:
            self.输出(f"※ {原因}")
            return False, 原因

        返回值 = self.执行引擎函数(行动["引擎函数"])
        消耗大事 = False
        if 行动["键"] == "外交":
            # 外交菜单返回 "大事" / "轻量" / None —— 与引擎语义一致
            消耗大事 = (返回值 == "大事")
        elif 行动["大事"]:
            消耗大事 = bool(返回值)
        if 消耗大事:
            self.大事已用 = True
            self.输出("（本回合大事名额已用，请结束本回合）")
        return True, ""

    def 结束回合(self):
        """推进一个回合：顺序与 主循环() 第 1378~1394 行逐行对齐。

        返回 (是否有结局, 结局文本或None)。
        """
        if self.结局:
            return True, self.结局
        self.执行引擎函数("结算回合")          # ① 13 步自动结算
        self._执行()                          # ② 打印新局势
        结局 = self.执行引擎函数("结局判定")     # ③ 结局判定
        if 结局 is not None:
            self.结局 = 结局
            self.输出("★" * 40)
            self.输出(结局)
            self.执行引擎函数("将领结局")       # ④ 将领结局汇总
            self.输出("★" * 40)
            return True, 结局
        self.执行引擎函数("推进日期")           # ⑤ 未结束则推进日期与回合数
        self.游戏.回合计数 += 1
        self.大事已用 = False                  # ⑥ 新回合重置"大事"名额
        return False, None

    def 自动演示一回合(self):
        """自动演示模式：调用引擎自身的 自动策略()，再结束回合（与 --demo 等价）。"""
        self.执行引擎函数("自动策略")
        return self.结束回合()

