    def 保存读档(self, 槽位):
        if 槽位 not in 槽位们:
            return False, f"无效槽位：{槽位}"
        成功, 提示 = save_manager.载入游戏(self.游戏.__dict__, 槽位)
        if 成功:
            self.结局 = None
