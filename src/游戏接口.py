"""游戏接口（引擎门面）—— 把《蜀汉突围》引擎包装成「可被图形界面驱动」的形式。

═══════════════════════════════════════════════════════════════════
【这个模块存在的原因】
引擎（src/蜀汉突围.py）原本只有一个「控制台外壳」：菜单用 print 打印、用 input 读答案。
要做图形界面，有两条错路和一条对路：

  ✗ 错路一：把判定规则抄一份到界面里 → 同一规则两处实现，126 项测试保护不到第二处。
  ✗ 错路二：重写一遍回合流程与菜单编排 → 行为必定与引擎逐渐分叉。
  ✓ 对路  ：界面只负责「把状态画出来」和「把玩家意图送回去」，
            流程与规则**全部交给引擎自己的函数**——靠两件事实现：

      1. 把引擎的 `input` 换成「界面弹对话框问玩家」的回调；
      2. 把引擎的 stdout 接到「界面的战报区」的回调。

  这正是 tests/ 里已经在用的注入式手法（`夹具.脚本输入` / `capture`），因此技术上是验证过的。

【本模块只负责三件"编排"性质的事，且每件都有测试兜底】
  1. 回合推进的记账：结算 → 打印局势 → 结局判定 →（未结束则）推进日期、回合数+1
     —— 与 主循环() 第 1363~1394 行的顺序逐行对齐，并有「与引擎自动演示逐回合比对」的回归用例；
  2. 「每回合一件大事」的名额记账 —— 与 决策阶段() 的 `已行大事` 同义，并有用例断言第二件大事被拒；
  3. 三个存档槽位（slot1 / slot2 / slot3）的读写与摘要。

【零第三方依赖】本模块只使用标准库（importlib / io / contextlib / sys / os）。
"""
