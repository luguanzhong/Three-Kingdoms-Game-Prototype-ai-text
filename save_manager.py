# -*- coding: utf-8 -*-
"""
存档 / 读档模块（M3 新增）。仅使用 Python 标准库（json / os / time）。

【设计要点】
1. 状态接口用「模块全局命名空间字典」传入（游戏侧写 `save_manager.保存游戏(globals(), ...)`），
   不依赖 sys.modules，因此在命令行运行与 importlib 自测加载下都能工作；
   恢复时容器原地清空重填、标量写回命名空间，保证既有引用不失效。
2. 存档为**可读的 JSON**，含版本字段 `存档版本`，另有 `游戏版本`、`保存时间`、
   `日期`（年月/回合/季节）、`三方势力`、`敌方城池`、`蜀汉城池`、`将领们`、`情报`、`全局`。
3. 写入采用「先写 .tmp 再 os.replace」的原子替换，避免写一半损坏已有存档。
4. 旧版本兼容：`迁移表` 为迁移钩子（当前无历史版本，故为空）；未登记迁移函数的旧版本
   会被**明确拒绝**并说明支持版本；比当前更新的版本同样拒绝。
5. 损坏存档：JSON 语法错、顶层非对象、缺必填字段、字段类型错、字段缺失等，逐项给出
   `存档损坏：<原因>，文件 <路径>` 形式的提示，绝不向上抛裸异常。
6. 零随机：本模块不导入随机库，只做确定性读写。
"""
import json
import os
import time

# —— 版本信息 ——
存档版本 = 1                     # 当前程序写出的存档版本
支持版本 = (1,)                  # 本程序能直接读取的存档版本
迁移表 = {}                      # {旧版本号: 迁移函数(数据)->数据}；暂无历史版本，留空备用

# —— 必填字段契约（缺字段或类型不符即判定存档损坏）——
必填顶层字段 = ("存档版本", "日期", "三方势力", "敌方城池", "蜀汉城池", "将领们", "情报", "全局")
必填日期字段 = ("当前年份", "当前月份", "回合计数", "季节")
势力必填字段 = {
    "蜀汉": ("兵力", "粮草", "魏国压力", "东吴好感", "民心", "精锐比例"),
    "曹魏": ("兵力", "粮草", "扩张倾向"),
    "东吴": ("兵力", "粮草", "观望态度"),
}
将领必填字段 = ("姓名", "统御", "智谋", "内政", "忠诚", "位置", "任务", "指令", "子任务",
                "状态", "据险", "重伤剩余")
# 城池类区块的必填字段与表示驻军的键名（敌方城池用"守军"，蜀汉城池用"兵力"）
城池区块契约 = {
    "敌方城池": {"必填": ("守军", "粮草", "归属"), "驻军键": "守军"},
    "蜀汉城池": {"必填": ("兵力", "粮草", "归属"), "驻军键": "兵力"},
}

# —— 全局项默认值：旧存档缺少这些键时按默认补齐（容错），类型不符才报错 ——
全局默认 = {
    "围攻状态": None, "连锁计时": 0, "事件日志": [], "已结盟": False,
    "东吴外交倾向": "观望", "东吴结盟对象": None, "东吴主动接触标记": False,
    "自动模式": False, "冬至提醒已触发": False, "魏军压境已触发": False,
    "东吴闭粮已触发": False, "国势衰微已触发": False,
}

# 存档名允许的字符（拒绝路径分隔符等，避免写到目录之外）
存档名允许字符 = set("0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ_-.")
存档名允许中文 = True
存档名最大长度 = 32


def 默认存档目录():
    """存档目录：本模块同级的 saves/（与启动时的工作目录无关）。"""
    return os.path.join(os.path.dirname(os.path.abspath(__file__)), "saves")


def 存档路径(存档名, 存档目录=None):
    """由存档名得到完整路径。"""
    return os.path.join(存档目录 or 默认存档目录(), 存档名 + ".json")


def 校验存档名(存档名):
    """存档名合法性检查，返回错误文本（合法则返回空串）。"""
    if not isinstance(存档名, str) or not 存档名:
        return "存档名不能为空。"
    if len(存档名) > 存档名最大长度:
        return f"存档名过长（最多 {存档名最大长度} 个字符）。"
    for 字 in 存档名:
        if 字 in 存档名允许字符 or (存档名允许中文 and "\u4e00" <= 字 <= "\u9fff"):
            continue
        return f"存档名含非法字符 {字!r}（只允许中文、字母、数字、下划线、短横线与点）。"
    return ""


def 类型名(值):
    """中文类型名（用于错误文案）。"""
    if isinstance(值, bool):
        return "布尔值"
    if isinstance(值, int):
        return "整数"
    if isinstance(值, float):
        return "小数"
    if isinstance(值, str):
        return "字符串"
    if isinstance(值, list):
        return "列表"
    if isinstance(值, dict):
        return "字典"
    if 值 is None:
        return "空值"
    return type(值).__name__


