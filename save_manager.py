def 列出存档(存档目录=None):
    """列出存档目录中的全部存档。返回 (是否成功, 提示文本, 列表)。"""
    目录 = 存档目录 or 默认存档目录()
    if not os.path.isdir(目录):
        return True, f"存档目录尚不存在（{目录}），还没有任何存档。", []
    条目 = []
    for 文件名 in sorted(os.listdir(目录)):
        if not 文件名.endswith(".json"):
            continue
        路径 = os.path.join(目录, 文件名)
        项 = {"存档名": 文件名[:-5], "路径": 路径, "状态": "正常", "保存时间": "", "摘要": ""}
        try:
            with open(路径, "r", encoding="utf-8") as 文件:
                数据 = json.load(文件)
            错误 = 校验存档(数据)
            if 错误:
                项["状态"] = f"损坏（{len(错误)} 处问题）"
            else:
                日期 = 数据["日期"]
                项["保存时间"] = 数据.get("保存时间", "")
                项["摘要"] = f"存档版本 {数据['存档版本']} · 第 {日期['回合计数']} 回合 · " \
                             f"{日期['当前年份']}年{日期['当前月份']}月 · 蜀汉兵力 {数据['三方势力']['蜀汉']['兵力']}"
        except (json.JSONDecodeError, OSError):
            项["状态"] = "损坏（无法解析）"
        条目.append(项)
    if not 条目:
        return True, f"存档目录为空（{目录}）。", []
    return True, f"共 {len(条目)} 个存档（{目录}）。", 条目


