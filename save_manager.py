def 采集状态(命名空间):
    """把游戏模块的全局命名空间采集为可序列化字典（深拷贝，不改变游戏状态）。"""
    return {
        "存档版本": 存档版本,
        "游戏版本": 命名空间.get("游戏版本", "未知"),
        "保存时间": time.strftime("%Y-%m-%d %H:%M:%S"),
        "日期": {
            "当前年份": 命名空间["当前年份"],
            "当前月份": 命名空间["当前月份"],
            "回合计数": 命名空间["回合计数"],
            "季节": 命名空间["季节"],
        },
        "三方势力": {
            "蜀汉": dict(命名空间["蜀汉"]),
            "曹魏": dict(命名空间["曹魏"]),
            "东吴": dict(命名空间["东吴"]),
        },
        "敌方城池": {城: dict(内容) for 城, 内容 in 命名空间["敌方城池"].items()},
        "蜀汉城池": {城: dict(内容) for 城, 内容 in 命名空间["蜀汉城池"].items()},
        "将领们": [dict(将领) for 将领 in 命名空间["将领们"]],
        "情报": dict(命名空间["情报"]),
        "全局": {键: (list(值) if isinstance(值, list) else 值)
                 for 键, 值 in 命名空间["全局"].items()},
    }


def 应用状态(命名空间, 数据):
    """把存档数据恢复到命名空间：容器原地清空重填、标量写回，保持引用不失效。"""
    # 标量：直接写回全局命名空间（函数按名字查找时会读到新值）
    日期 = 数据["日期"]
    命名空间["当前年份"] = 日期["当前年份"]
    命名空间["当前月份"] = 日期["当前月份"]
    命名空间["回合计数"] = 日期["回合计数"]
    命名空间["季节"] = 日期["季节"]

    # 容器：原地更新
    for 势力 in ("蜀汉", "曹魏", "东吴"):
        命名空间[势力].clear()
        命名空间[势力].update(数据["三方势力"][势力])

    for 城字典名 in ("敌方城池", "蜀汉城池"):
        容器 = 命名空间[城字典名]
        容器.clear()
        for 城, 内容 in 数据[城字典名].items():
            容器[城] = dict(内容)

    命名空间["将领们"][:] = [dict(将领) for 将领 in 数据["将领们"]]

    命名空间["情报"].clear()
    命名空间["情报"].update(数据["情报"])

    新全局 = dict(全局默认)
    新全局.update(数据["全局"])
    命名空间["全局"].clear()
    命名空间["全局"].update(新全局)


