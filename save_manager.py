def 校验整数(数据, 键, 错误, 位置):
    """校验一个应为整数的字段（拒绝布尔；键不存在时跳过，缺失由必填检查负责）。"""
    if 键 not in 数据:
        return
    值 = 数据.get(键)
    if isinstance(值, bool) or not isinstance(值, int):
        错误.append(f"{位置}.{键} 应为整数，实际 {值!r}（{类型名(值)}）")


def 校验存档(数据):
    """校验存档结构，返回错误列表（空列表表示可用）。"""
    错误 = []
    if not isinstance(数据, dict):
        错误.append(f"顶层应为 JSON 对象，实际 {类型名(数据)}")
        return 错误

    for 键 in 必填顶层字段:
        if 键 not in 数据:
            错误.append(f"缺少字段 {键}")
    if 错误:
        return 错误

    # 版本
    if isinstance(数据["存档版本"], bool) or not isinstance(数据["存档版本"], int):
        错误.append(f"存档版本 应为整数，实际 {数据['存档版本']!r}（{类型名(数据['存档版本'])}）")

    # 日期
    日期 = 数据["日期"]
    if not isinstance(日期, dict):
        错误.append(f"日期 应为对象，实际 {类型名(日期)}")
    else:
        for 键 in 必填日期字段:
            if 键 not in 日期:
                错误.append(f"日期.缺少字段 {键}")
        校验整数(日期, "当前年份", 错误, "日期")
        校验整数(日期, "当前月份", 错误, "日期")
        校验整数(日期, "回合计数", 错误, "日期")
        if "季节" in 日期 and not isinstance(日期["季节"], str):
            错误.append(f"日期.季节 应为字符串，实际 {类型名(日期['季节'])}")
        if isinstance(日期.get("当前月份"), int) and not 1 <= 日期["当前月份"] <= 12:
            错误.append(f"日期.当前月份 应在 1~12，实际 {日期['当前月份']}")

    # 三方势力
    三方 = 数据["三方势力"]
    if not isinstance(三方, dict):
        错误.append(f"三方势力 应为对象，实际 {类型名(三方)}")
    else:
        for 势力, 字段们 in 势力必填字段.items():
            内容 = 三方.get(势力)
            if not isinstance(内容, dict):
                错误.append(f"三方势力.{势力} 应为对象，实际 {类型名(内容)}")
                continue
            for 键 in 字段们:
                if 键 not in 内容:
                    错误.append(f"三方势力.{势力}.缺少字段 {键}")
                else:
                    校验整数(内容, 键, 错误, f"三方势力.{势力}")

    # 敌方城池 / 蜀汉城池（两者必填字段不同：前者"守军"、后者"兵力"）
    for 城字典名, 契约 in 城池区块契约.items():
        城字典 = 数据[城字典名]
        if not isinstance(城字典, dict):
            错误.append(f"{城字典名} 应为对象，实际 {类型名(城字典)}")
            continue
        if not 城字典:
            错误.append(f"{城字典名} 为空（至少需要一座城池）")
        for 城, 内容 in 城字典.items():
            if not isinstance(内容, dict):
                错误.append(f"{城字典名}.{城} 应为对象，实际 {类型名(内容)}")
                continue
            for 键 in 契约["必填"]:
                if 键 not in 内容:
                    错误.append(f"{城字典名}.{城}.缺少字段 {键}")
            校验整数(内容, 契约["驻军键"], 错误, f"{城字典名}.{城}")
            校验整数(内容, "粮草", 错误, f"{城字典名}.{城}")
            if "归属" in 内容 and not isinstance(内容["归属"], str):
                错误.append(f"{城字典名}.{城}.归属 应为字符串，实际 {类型名(内容['归属'])}")
            守将 = 内容.get("守将")
            if 守将 is not None and not isinstance(守将, (dict, str)):
                错误.append(f"{城字典名}.{城}.守将 应为对象/字符串/空值，实际 {类型名(守将)}")

    # 将领们
    将领们 = 数据["将领们"]
    if not isinstance(将领们, list):
        错误.append(f"将领们 应为列表，实际 {类型名(将领们)}")
    elif not 将领们:
        错误.append("将领们 为空列表（至少需要一名将领）")
    else:
        for 序号, 将领 in enumerate(将领们, 1):
            if not isinstance(将领, dict):
                错误.append(f"将领们 第 {序号} 项应为对象，实际 {类型名(将领)}")
                continue
            for 键 in 将领必填字段:
                if 键 not in 将领:
                    错误.append(f"将领们 第 {序号} 项（{将领.get('姓名', '未命名')}）缺少字段 {键}")
            for 键 in ("统御", "智谋", "内政", "忠诚", "重伤剩余"):
                if 键 in 将领:
                    校验整数(将领, 键, 错误, f"将领们[{将领.get('姓名', 序号)}]")

    # 情报
    情报 = 数据["情报"]
    if not isinstance(情报, dict):
        错误.append(f"情报 应为对象，实际 {类型名(情报)}")
    else:
        for 键 in ("粮道情报", "风向情报"):
            if 键 not in 情报:
                错误.append(f"情报.缺少字段 {键}")
            elif not isinstance(情报[键], bool):
                错误.append(f"情报.{键} 应为布尔值，实际 {类型名(情报[键])}")

    # 全局
    全局 = 数据["全局"]
    if not isinstance(全局, dict):
        错误.append(f"全局 应为对象，实际 {类型名(全局)}")
    else:
        for 键, 默认值 in 全局默认.items():
            if 键 not in 全局:
                continue                      # 旧存档缺项 → 恢复时按默认补齐
            if 默认值 is None:
                continue
            if isinstance(默认值, bool) and not isinstance(全局[键], bool):
                错误.append(f"全局.{键} 应为布尔值，实际 {类型名(全局[键])}")
            elif isinstance(默认值, int) and not isinstance(默认值, bool) \
                    and (isinstance(全局[键], bool) or not isinstance(全局[键], int)):
                错误.append(f"全局.{键} 应为整数，实际 {类型名(全局[键])}")
            elif isinstance(默认值, list) and not isinstance(全局[键], list):
                错误.append(f"全局.{键} 应为列表，实际 {类型名(全局[键])}")
        围攻 = 全局.get("围攻状态")
        if 围攻 is not None and not isinstance(围攻, dict):
            错误.append(f"全局.围攻状态 应为对象或空值，实际 {类型名(围攻)}")

    return 错误


