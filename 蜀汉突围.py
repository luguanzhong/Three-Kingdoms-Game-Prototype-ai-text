def 计谋_侦查粮道():
    """前置：粮草 ≥ 侦查成本（config/schemes.json 计谋.侦查.粮草消耗）。消耗：粮草 + 本回合。
    效果：获得粮道情报（劫粮道的前置条件，键名见 计谋.劫粮道.前置情报）。"""
    成本 = 配置["计谋"]["侦查"]["粮草消耗"]
    情报键 = 配置["计谋"]["劫粮道"]["前置情报"]
    if 蜀汉["粮草"] < 成本:
        return False, f"前置条件不满足：粮草不足{成本}，派不出斥候。"
