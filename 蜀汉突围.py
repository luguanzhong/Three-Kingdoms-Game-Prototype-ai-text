def 中文数字(数字):
    """把1~99的整数转成中文数字（如 13 → 十三），供日期显示使用。"""
    表 = "一二三四五六七八九"
    if 数字 < 10:
        return 表[数字 - 1]
    if 数字 < 20:
        return "十" + ("" if 数字 == 10 else 表[数字 - 11])
    if 数字 % 10 == 0:
        return 表[数字 // 10 - 1] + "十"
    return 表[数字 // 10 - 1] + "十" + 表[数字 % 10 - 1]


