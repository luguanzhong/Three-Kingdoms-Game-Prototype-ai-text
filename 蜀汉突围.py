# 模块2：军事/计谋确定性判定函数
# ═══════════════════════════════════════════════════════════════════════════
# 【本模块的总原则】所有函数都是"确定性判定"：
#   输入一组明确的条件 → 经过纯算术比较 → 输出唯一确定的结果。
#   全模块不导入任何随机库、不调用任何随机函数，也没有隐藏的骰子。
#   军事行动只看"有效兵力"对比（有效兵力 = 兵力 × (1 + 精锐比例/100)），
#   计谋只看"前置条件是否达成"。
#
# 【关于需求3.3中百分比伤亡的说明】需求原文对"死守/默认驻守"给出了百分比结局，
#   与"严禁随机死亡"的总原则冲突。为保证全局零随机，本原型把百分比结局
#   "确定化"为固定结局（取各分支中最能保留"代价感"的一种），详见城破伤亡判定。

def 计算强攻判定(进攻兵力, 守军):
    """需求5.1：兵力 > 守军×倍率下限 → 强攻100%胜利（损失 = 守军×损失系数）。
    阈值取自 config/battle.json（战斗.强攻）；纯数值比较，无随机。返回(是否必胜, 预计损失, 说明)。"""
    强攻 = 配置["战斗"]["强攻"]
    if 进攻兵力 > 守军 * 强攻["兵力倍率下限"]:
        损失 = int(守军 * 强攻["损失系数"])
        return True, 损失, f"强攻必胜！但需付出惨重代价，预计损失兵力 {损失}。"
    return False, 0, f"强攻无必胜把握（需进攻兵力 > 守军×{强攻['兵力倍率下限']} = {int(守军 * 强攻['兵力倍率下限'])}）。"


def 计算围攻判定(进攻兵力, 守军):
    """需求5.1：兵力 > 守军×倍率下限 → 围攻100%胜利（需消耗数回合粮草）。
    阈值取自 config/battle.json（战斗.围攻）。无随机。"""
    围攻规则 = 配置["战斗"]["围攻"]
    if 进攻兵力 > 守军 * 围攻规则["兵力倍率下限"]:
        return True, f"围攻可行：围而不攻，{围攻规则['回合数']}回合后敌军粮尽投降（需持续消耗粮草）。"
    return False, f"围攻不可行（需进攻兵力 > 守军×{围攻规则['兵力倍率下限']} = {int(守军 * 围攻规则['兵力倍率下限'])}）。"


def 计算必败判定(进攻兵力, 守军):
    """需求5.1：兵力 < 守军×倍率上限 → 此战必败，系统禁止送死（唯一例外：死士突袭）。
    阈值取自 config/battle.json（战斗.必败）。"""
    if 进攻兵力 < 守军 * 配置["战斗"]["必败"]["兵力倍率上限"]:
        return True, "此战必败！系统禁止无意义送死。唯一例外是【死士突袭】——那将必定牺牲将领或部队。"
    return False, "此战无必胜把握（兵力不足守军的强攻/围攻阈值），系统禁止盲目进攻。"


