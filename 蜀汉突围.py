def 攻占城池(目标, 领将, 损失系数, 方式):
    """占领城池：立即收益 + 立即代价 + 连锁事件（需求5.3）。
    损失系数：强攻0.8（需求原文）、围攻0.3（MVP补充，围攻损耗较小）。
    v0.2.0：目标为洛阳时走"北伐大捷"特殊结算（跳过常规连锁，见结局判定）。"""
    if 目标 == "洛阳":
        # v0.2.0：攻占洛阳——北伐终极目标。系数取自 config/battle.json（战斗.北伐大捷）
        大捷 = 配置["战斗"]["北伐大捷"]
        曹魏["兵力"] = int(曹魏["兵力"] * 大捷["曹魏兵力系数"])
        东吴["观望态度"] = 0
        蜀汉["兵力"] += 大捷["蜀汉兵力增加"]
        敌方城池["洛阳"]["归属"] = "蜀汉"
        敌方城池["洛阳"]["守将"] = None
        记录("【北伐大捷】汉军攻克洛阳！曹魏中枢崩溃，天下震动！")
        return
    守军 = 敌方城池[目标]["守军"]
    损失 = int(守军 * 损失系数)
    if 领将["任务"] == "北伐先锋":
        损失 = int(损失 * 配置["战斗"]["北伐先锋"]["损耗系数"])   # 北伐先锋：进攻兵力损耗减少
    蜀汉["兵力"] = max(0, 蜀汉["兵力"] - 损失)
    收编 = int(守军 * 配置["战斗"]["收编"]["守军比例"])           # 收编降卒
    蜀汉["兵力"] += 收编
    缴粮 = 敌方城池[目标]["粮草"]
    蜀汉["粮草"] += 缴粮
    if 敌方城池[目标]["守将"] is not None:
        记录(f"{目标}守将{敌方城池[目标]['守将']['姓名']}乱军之中殒命。")
    敌方城池[目标]["守将"] = None
    敌方城池[目标]["归属"] = "蜀汉"
    记录(f"{领将['姓名']}{方式}攻占{目标}！损兵{损失}，收编降卒{收编}，缴粮{缴粮}。")
    # —— 连锁事件1：东吴忌惮（立即发生）——
    蜀汉["东吴好感"] = max(0, 蜀汉["东吴好感"] - 20)
    记录("连锁事件：东吴对蜀汉扩张速度忌惮（东吴好感-20），要求割让边境土地！")
    print("\n【连锁事件】东吴使者：'玄德公新得大城，吴侯愿以边境之地为质，共安盟好。'")
    print("A. 割地——粮草-30，东吴观望-10（稳住东吴）")
    print("B. 强硬拒绝——东吴观望+25（东吴或生异心，可能断盟背刺）")
    抉择 = input("请选择A/B：").strip().upper()
    if 抉择 == "A":
        蜀汉["粮草"] = max(0, 蜀汉["粮草"] - 30)
        东吴["观望态度"] = max(0, 东吴["观望态度"] - 10)
        记录("蜀汉割地求和（粮草-30，东吴观望-10）。")
    else:
        东吴["观望态度"] += 25
        记录("蜀汉强硬拒绝！东吴进入敌对观望（观望+25）。")
    # —— 连锁事件2：3回合后曹魏邻线增兵（计时器，见结算回合）——
    if 全局["连锁计时"] == 0:
        全局["连锁计时"] = 3
        记录("预计3回合后，曹魏将在邻线增兵报复……")


