def 计算势力值(势力):
    """v0.3.0：综合势力值 = 兵力 + 城池数×城池权重 + 将领总统御×统御权重。
    权重取自 config/diplomacy.json（外交.势力值）；确定性，零随机。
    曹魏将领只统计仍在曹魏控制城池的守将（无统御字段者按0计）。"""
    权重 = 配置["外交"]["势力值"]
    if 势力 == "蜀汉":
        兵力 = 蜀汉["兵力"]
        城池数 = 蜀汉控制城池数()
        总统御 = sum(将["统御"] for 将 in 将领们 if 将["状态"] != "已殁")
    else:
        兵力 = 曹魏["兵力"]
        城池数 = sum(1 for 城 in 敌方城池 if 敌方城池[城]["归属"] == "曹魏")
        总统御 = sum(敌方城池[城]["守将"].get("统御", 0) for 城 in 敌方城池
                    if 敌方城池[城]["归属"] == "曹魏" and 敌方城池[城]["守将"] is not None)
    return 兵力 + 城池数 * 权重["城池权重"] + 总统御 * 权重["统御权重"]


def 防御加成计算(将领):
    """确定性防御加成公式（系数取自 config/battle.json 战斗.防御加成）：
    镇守城池：统御×镇守城池系数；驻守险关：统御×驻守险关系数（效果翻倍）；
    死守+死守加成、提前撤退-提前撤退减成（让守城指令存在战前权衡）；
    已据险而守：总加成再×据险翻倍（据险而守，防御翻倍）。"""
    系数 = 配置["战斗"]["防御加成"]
    if 将领 is None or 将领["状态"] != "正常":
        return 0.0
    加成 = 0.0
    if 将领["任务"] == "镇守城池":
        加成 += 将领["统御"] * 系数["镇守城池系数"]
    elif 将领["任务"] == "驻守险关":
        加成 += 将领["统御"] * 系数["驻守险关系数"]
    if 将领["指令"] == "死守":
        加成 += 系数["死守加成"]
    elif 将领["指令"] == "提前撤退":
        加成 -= 系数["提前撤退减成"]
    if 将领["据险"]:
        加成 *= 系数["据险翻倍"]
    return 加成


def 攻城结算(进攻兵力, 守军, 防守将领):
    """通用确定性城池攻防：
    守值 = 守军 × (1 + 防守将领防御加成)；破城阈值取自 config/battle.json（战斗.攻破城池）。
    进攻兵力 > 守值×兵力倍率下限 → 城破（返回True）；否则击退（返回False）。零随机。"""
    守值 = int(守军 * (1 + 防御加成计算(防守将领)))
    if 进攻兵力 > 守值 * 配置["战斗"]["攻破城池"]["兵力倍率下限"]:
        return True, 守值
    return False, 守值


def 城破伤亡判定(将领, 指令):
    """需求3.3的确定性化：城破时将领结局100%由玩家预设指令决定，严禁随机。
    确定化规则（原百分比结局在注释中保留对照）：
      提前撤退 → 100%存活退回后方，但民心下降（由调用方扣除）。
      死守     → 统御≥8：重伤撤离（原型70%战死/30%重伤，取可保留的"重伤"结局）；
                  统御<8：战死（原型90%战死，确定化为100%）。
      默认驻守 → 被俘（原型50%被俘/30%战死/20%突围，取"被俘"，可用粮草赎回）。
    """
    if 指令 == "提前撤退":
        return f"{将领['姓名']}依令提前撤退，安然退回后方（100%存活，民心将下降）。"
    if 指令 == "死守":
        if 将领["统御"] >= 8:
            将领["状态"] = "重伤"
            将领["重伤剩余"] = 1
            return f"{将领['姓名']}死守孤城，身被数创，幸得亲兵拼死救出——重伤撤离，需休整1回合。"
        将领["状态"] = "已殁"
        return f"{将领['姓名']}死守不退，力战而亡！"
    # 默认驻守（未预设指令）→ 确定化为被俘
    将领["状态"] = "被俘"
    return f"{将领['姓名']}未得明确指令，城破被俘！可用粮草40在外交菜单赎回。"


