# -*- coding: utf-8 -*-
"""官方底图配准结果的回归用例（config/底图配准.json）。

为什么值得单独测：配准是"官方底图"这条链路的命门。系数错一点点，底图与州郡界就会整体错位，
而错位的图**看上去仍然很像样**，最难用眼睛发现。这里用可计算的量把它钉住：

1. 文件结构与"图像宽高"必须和仓库里那张图一致（换图不重跑工具就会被抓出来）
2. 拟合变换必须与游戏自己的投影**严格自洽**（往返无损 + 六参数与投影一致）
3. 拟合质量必须达标（平均误差、命中率）—— 将来重跑工具如果配歪了，这里会红
4. 图幅范围必须落在常识范围内（一条独立于拟合过程的自检）
"""
import importlib.util
import json
import os
import sys
import unittest

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import 夹具  # noqa: E402

sys.path.insert(0, os.path.join(夹具.仓库根目录, "ui"))
import 地图  # noqa: E402

配准路径 = os.path.join(夹具.仓库根目录, "config", "底图配准.json")

规格 = importlib.util.spec_from_file_location(
    "底图配准", os.path.join(夹具.仓库根目录, "tools", "底图配准.py"))
配准 = importlib.util.module_from_spec(规格)
规格.loader.exec_module(配准)


def 读配准():
    if not os.path.isfile(配准路径):
        raise unittest.SkipTest("还没有 config/底图配准.json（先跑 python tools/底图配准.py）")
    with open(配准路径, encoding="utf-8") as 文件:
        return json.load(文件)


def 参数们(数据):
    拟 = 数据["拟合变换"]
    return [拟["圆锥常数"], 拟["缩放"], 拟["旋转"], 拟["平移"][0], 拟["平移"][1], 拟["中央经线"]]


class 底图配准(unittest.TestCase):

    def setUp(self):
        self.数据 = 读配准()

    def test_图像存在且尺寸一致(self):
        """换底图后必须重跑工具 —— 否则这里的尺寸对不上，会直接判红。"""
        相对 = self.数据["图像"]
        路径 = os.path.join(夹具.仓库根目录, 相对)
        self.assertTrue(os.path.isfile(路径), f"配准文件里写的底图不存在：{相对}")
        信息, _, _ = 配准.读PNG块们(路径)
        self.assertEqual([信息["宽"], 信息["高"]], self.数据["图像宽高"],
                         "底图尺寸与配准文件不一致（换了图没重跑配准？）")

    def test_投影参数与游戏配置一致(self):
        """配准是按当时的投影算出来的；投影改了就必须重跑，否则两套坐标会对不上。"""
        投影 = self.数据["投影"]
        for 键, 值 in (("中央经线", 地图.中央经线), ("圆锥常数", 地图.圆锥常数),
                      ("参考纬度", 地图.参考纬度), ("缩放", 地图.缩放)):
            self.assertAlmostEqual(投影[键], 值, places=9,
                                   msg=f"配准文件里的「{键}」与 config/投影.json 不一致，请重跑配准")

    def test_像素经纬往返无损(self):
        """拟合变换必须是严格互逆的（否则悬停查经纬、点图定位都会慢慢漂）。"""
        参数 = 参数们(self.数据)
        for 经度, 纬度 in ((116.4, 39.9), (87.6, 43.8), (104.1, 30.6), (121.5, 31.2)):
            u, v = 配准.投影到像素(参数, 经度, 纬度)
            回 = 配准.像素到经纬(参数, u, v)
            self.assertAlmostEqual(回[0], 经度, places=8)
            self.assertAlmostEqual(回[1], 纬度, places=8)

    def test_六参数与投影一致(self):
        """写给游戏用的六参数仿射，必须真的能把图像像素换算成 game 自己的世界坐标。"""
        a, b, c, d, e, f = self.数据["像素到世界"]["系数"]
        参数 = 参数们(self.数据)
        最大差 = 0.0
        for 经度, 纬度 in ((116.4, 39.9), (104.07, 30.57), (121.47, 31.23), (87.62, 43.83),
                          (113.26, 23.13), (126.63, 45.75)):
            u, v = 配准.投影到像素(参数, 经度, 纬度)
            世界x, 世界y = a * u + b * v + c, d * u + e * v + f
            应x, 应y = 地图.投影(经度, 纬度)
            最大差 = max(最大差, abs(世界x - 应x), abs(世界y - 应y))
        self.assertLess(最大差, 1.0,
                        f"六参数换算与直接投影相差 {最大差:.3f} 世界像素，底图会与州郡界错位")

    def test_拟合质量达标(self):
        """把"配准够不够准"钉成硬指标：故意留出余量，但明显偏了就要红。"""
        误差 = self.数据["误差"]
        self.assertLess(误差["平均_像素"], 6.0,
                        f"平均误差 {误差['平均_像素']} 像素偏大（≈{误差['平均_千米']} 千米）")
        命中 = 误差["命中率"]
        self.assertGreater(命中["境内点落在着色区"], 0.85, "境内参照点落在版图外的太多")
        self.assertGreater(命中["境外点落在白色区"], 0.80, "境外参照点压在版图上的太多")

    def test_反算图幅落在常识范围(self):
        """图像四角反算出的经纬度必须像一张中国地图 —— 这条不依赖拟合过程本身。"""
        经度 = self.数据["反算图幅"]["经度"]
        纬度 = self.数据["反算图幅"]["纬度"]
        self.assertTrue(60 <= 经度[0] <= 80, f"西边界 {经度[0]} 不像中国图的西边界")
        self.assertTrue(125 <= 经度[1] <= 155, f"东边界 {经度[1]} 不像中国图的东边界")
        self.assertTrue(10 <= 纬度[0] <= 22, f"南边界 {纬度[0]} 不像中国图的南边界")
        self.assertTrue(46 <= 纬度[1] <= 58, f"北边界 {纬度[1]} 不像中国图的北边界")

    def test_参照点落在版图内的比例高(self):
        """再用一批"城市级"地标做一次抽样 —— 与拟合用的栅格点不同源，算交叉验证。"""
        参数 = 参数们(self.数据)
        元, 掩膜 = 配准.取掩膜(os.path.join(夹具.仓库根目录, self.数据["图像"]))
        步长, 小宽 = 元["步长"], 元["小宽"]
        城市 = [("北京", 116.41, 39.90), ("西安", 108.95, 34.27), ("成都", 104.07, 30.57),
               ("广州", 113.26, 23.13), ("乌鲁木齐", 87.62, 43.83), ("拉萨", 91.14, 29.65),
               ("哈尔滨", 126.63, 45.75), ("郑州", 113.62, 34.75), ("武汉", 114.30, 30.60),
               ("长沙", 112.94, 28.23), ("南宁", 108.37, 22.82), ("海口", 110.35, 20.02),
               ("昆明", 102.83, 24.88), ("兰州", 103.83, 36.06), ("银川", 106.23, 38.49),
               ("呼和浩特", 111.75, 40.84), ("齐齐哈尔", 123.92, 47.35)]
        命中 = 0
        for 名, 经度, 纬度 in 城市:
            u, v = 配准.投影到像素(参数, 经度, 纬度)
            小u, 小v = int(u / 步长), int(v / 步长)
            if not (0 <= 小u < 小宽 and 0 <= 小v < 元["小高"]):
                continue
            陆 = 海 = 0
            for 偏v in range(-4, 5):
                for 偏u in range(-4, 5):
                    值 = 掩膜[(小v + 偏v) * 小宽 + (小u + 偏u)]
                    陆 += 1 if 值 == 1 else 0
                    海 += 1 if 值 == 0 else 0
            if 陆 > 海:
                命中 += 1
        self.assertGreaterEqual(命中, 15, f"只有 {命中}/{len(城市)} 个城市落在版图内，配准可能偏了")


if __name__ == "__main__":
    unittest.main(verbosity=2)
