def 字符画(元, 掩膜, 列数=100, 行数=36):
    """把掩膜压成字符画打印出来 —— 用来肉眼确认"陆/海判据"没判反（应能看出中国轮廓）。"""
    小宽, 小高 = 元["小宽"], 元["小高"]
    print(f"掩膜字符画（# 陆地　. 海洋　? 无法判定）　{小宽}×{小高} → {列数}×{行数}")
    for 行号 in range(行数):
        v0 = int(行号 * 小高 / 行数)
        v1 = max(int((行号 + 1) * 小高 / 行数), v0 + 1)
        文本 = ""
        for 列号 in range(列数):
            u0 = int(列号 * 小宽 / 列数)
            u1 = max(int((列号 + 1) * 小宽 / 列数), u0 + 1)
            陆 = 海 = 他 = 0
            for v in range(v0, min(v1, 小高)):
                for u in range(u0, min(u1, 小宽)):
                    格 = 掩膜[v * 小宽 + u]
                    if 格 == 1:
                        陆 += 1
                    elif 格 == 0:
                        海 += 1
                    else:
                        他 += 1
            if 他 > 陆 + 海:
                文本 += "?"
            elif 陆 >= 海:
                文本 += "#"
            else:
                文本 += "."
        print("  " + 文本)


