def 抽查系数(系数, 参数):
    """用写出的六参数把几个已知经纬度换算成像素，和拟合变换直接算的结果比对。"""
    a, b, c, d, e, f = 系数
    最大差 = 0.0
    for 经度, 纬度 in ((116.4, 39.9), (104.07, 30.57), (121.47, 31.23), (87.62, 43.83)):
        u, v = 投影到像素(参数, 经度, 纬度)
        世界x, 世界y = a * u + b * v + c, d * u + e * v + f
        应x, 应y = 地图.投影(经度, 纬度)
        最大差 = max(最大差, abs(世界x - 应x), abs(世界y - 应y))
    return f"四个城市用系数换算与直接投影的最大偏差 {最大差:.2e} 世界像素"


def 生成叠加图(参数, 元, 内点们, 外点们, 底图路径, 输出):
    """把底图降采样后叠上"按配准投影出来的中国境内参照点"，输出 PNG 供人工/机器核验。"""
    步 = 3
    宽, 高 = 元["宽"] // 步, 元["高"] // 步
    print(f"生成叠加核验图 {宽}×{高}…")
    信息, 压缩数据, 调色板 = 读PNG块们(底图路径)
    行字节 = 信息["宽"] * 通道数(信息["颜色类型"])
    原始 = zlib.decompress(压缩数据)
    画布 = []
    位置, 上一行 = 0, bytearray(行字节)
    for y in range(信息["高"]):
        滤波类型 = 原始[位置]
        行 = bytearray(原始[位置 + 1:位置 + 1 + 行字节])
        位置 += 1 + 行字节
        if 滤波类型 == 1:
            for i in range(通道数(信息["颜色类型"]), 行字节):
                行[i] = (行[i] + 行[i - 通道数(信息["颜色类型"])]) & 0xFF
        elif 滤波类型 == 2:
            for i in range(行字节):
                行[i] = (行[i] + 上一行[i]) & 0xFF
        elif 滤波类型 == 3:
            for i in range(行字节):
                左 = 行[i - 3] if i >= 3 else 0
                行[i] = (行[i] + ((左 + 上一行[i]) >> 1)) & 0xFF
        elif 滤波类型 == 4:
            for i in range(行字节):
                左 = 行[i - 3] if i >= 3 else 0
                左上 = 上一行[i - 3] if i >= 3 else 0
                行[i] = (行[i] + _帕斯滤波(左, 上一行[i], 左上)) & 0xFF
        上一行 = 行
        if y % 步 == 0:
            行数据 = bytearray()
            每像素 = 通道数(信息["颜色类型"])
            for x in range(0, 信息["宽"], 步):
                行数据 += 行[x * 每像素: x * 每像素 + 3]
            画布.append(行数据)
    # 叠红点：按配准把"中国境内参照点"投影到底图上（红点应铺满底图的着色区）
    数量 = 0
    for 经度, 纬度 in 内点们:
        u, v = 投影到像素(参数, 经度, 纬度)
        x, y = int(u / 步), int(v / 步)
        if 0 <= x < 宽 and 0 <= y < 高:
            画布[y][x * 3: x * 3 + 3] = b"\xff\x00\x00"
            数量 += 1
    # 再叠一圈蓝点：国界外一圈的参照点（蓝点应落在白色区，不该压在着色区里）
    for 经度, 纬度 in 外点们:
        u, v = 投影到像素(参数, 经度, 纬度)
        x, y = int(u / 步), int(v / 步)
        if 0 <= x < 宽 and 0 <= y < 高:
            画布[y][x * 3: x * 3 + 3] = b"\x00\x40\xff"
    os.makedirs(os.path.dirname(输出), exist_ok=True)
    写PNG(输出, 宽, 高, 画布)
    print(f"  叠加核验图已写出：{os.path.relpath(输出, 根目录)}"
          f"（红点 = 境内参照点 {数量} 个，蓝点 = 境外参照点）")


