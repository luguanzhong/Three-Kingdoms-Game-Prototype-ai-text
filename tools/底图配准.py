def 写PNG(路径, 宽, 高, 行们):
    """把若干行 RGB 字节写成 PNG（仅标准库 zlib）。"""
    原始 = b"".join(b"\x00" + bytes(行) for 行 in 行们)

    def 块(类型, 内容):
        return (struct.pack(">I", len(内容)) + 类型 + 内容
                + struct.pack(">I", zlib.crc32(类型 + 内容) & 0xFFFFFFFF))
    数据 = (b"\x89PNG\r\n\x1a\n"
            + 块(b"IHDR", struct.pack(">IIBBBBB", 宽, 高, 8, 2, 0, 0, 0))
            + 块(b"IDAT", zlib.compress(原始, 6))
            + 块(b"IEND", b""))
    with open(路径, "wb") as 文件:
        文件.write(数据)


