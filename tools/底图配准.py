def 连通域(元, 掩膜, 最小格数=120):
    """把陆地块做连通域标记，丢掉太小的（文字、图例色块、注记），返回 (新掩膜, 统计)。

    为什么必须做：图廓外的图名、图例、比例尺都是"有色像素"，在掩膜里就是一个个孤立的
    陆地小岛；不剔掉的话它们会在海里造出一圈圈假的"海陆交界"，把拟合往错处拉。
    """
    小宽, 小高 = 元["小宽"], 元["小高"]
    标签 = [0] * (小宽 * 小高)
    域们 = []
    序号 = 0
    for 起 in range(小宽 * 小高):
        if 掩膜[起] != 1 or 标签[起]:
            continue
        序号 += 1
        栈 = [起]
        标签[起] = 序号
        格们 = []
        while 栈:
            格 = 栈.pop()
            格们.append(格)
            u, v = 格 % 小宽, 格 // 小宽
            for 邻 in ((u - 1, v), (u + 1, v), (u, v - 1), (u, v + 1)):
                if 0 <= 邻[0] < 小宽 and 0 <= 邻[1] < 小高:
                    邻格 = 邻[1] * 小宽 + 邻[0]
                    if 掩膜[邻格] == 1 and not 标签[邻格]:
                        标签[邻格] = 序号
                        栈.append(邻格)
        域们.append(格们)
    域们.sort(key=len, reverse=True)
    新掩膜 = bytearray(掩膜)
    for 域 in 域们:
        if len(域) < 最小格数:
            for 格 in 域:
                新掩膜[格] = 255
    统计 = []
    for 域 in 域们[:12]:
        us = [格 % 小宽 for 格 in 域]
        vs = [格 // 小宽 for 格 in 域]
        统计.append({"格数": len(域), "外接框": [min(us), min(vs), max(us), max(vs)]})
    return 新掩膜, 统计


