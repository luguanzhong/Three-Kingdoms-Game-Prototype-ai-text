def 下载图层(文件名, 说明):
    缓存 = os.path.join(tempfile.gettempdir(),
                       "mapdata_" + 文件名.replace(".geojson", "") + ".json")
    if os.path.isfile(缓存) and os.path.getsize(缓存) > 1000:
        try:
            with open(缓存, encoding="utf-8") as 文件:
                数据 = json.load(文件)
            print(f"参照数据取自缓存（{说明}）")
            return 数据
        except (OSError, json.JSONDecodeError):
            pass
    print(f"下载参照数据：{文件名}（{说明}）…")
    with urllib.request.urlopen(自然地球 + 文件名, timeout=180) as 响应:
        数据 = json.loads(响应.read().decode("utf-8"))
    with open(缓存, "w", encoding="utf-8") as 文件:
        json.dump(数据, 文件)
    return 数据


def 取中国环们():
    """从 Natural Earth 里取出中国（ADMIN=China）的全部环（外环 + 内环/洞）。"""
    数据 = 下载图层(国家图层, "Natural Earth 50m 国界，公有领域")
    要素 = None
    for 项 in 数据.get("features", []):
        属性 = 项.get("properties") or {}
        名 = (属性.get("ADMIN") or 属性.get("NAME") or "").strip()
        if 名 in ("China", "中华人民共和国", "中国"):
            要素 = 项
            break
    if 要素 is None:
        raise RuntimeError("在 Natural Earth 数据里没找到 China —— 数据格式可能变了")
    几何 = 要素.get("geometry") or {}
    环们 = []
    类 = 几何.get("type")
    if 类 == "Polygon":
        组 = [几何["coordinates"]]
    elif 类 == "MultiPolygon":
        组 = 几何["coordinates"]
    else:
        raise RuntimeError(f"China 的几何类型是 {类}，本工具只认识 Polygon / MultiPolygon")
    for 多边形 in 组:
        for 环 in 多边形:
            if len(环) >= 4:
                环们.append([(float(p[0]), float(p[1])) for p in 环])
    print(f"参照中国边界：{len(环们)} 个环，共 {sum(len(r) for r in 环们)} 个顶点")
    return 环们


def 栅格化(环们, 步长):
    """扫描线栅格化：返回落在环内的格子集合（偶奇规则，洞会自动被排除）。"""
    ys = [p[1] for 环 in 环们 for p in 环]
    y0, y1 = math.floor(min(ys) / 步长), math.ceil(max(ys) / 步长)
    在内 = set()
    for 行 in range(y0, y1 + 1):
        y = (行 + 0.5) * 步长
        交点 = []
        for 环 in 环们:
            for i in range(len(环) - 1):
                (xa, ya), (xb, yb) = 环[i], 环[i + 1]
                if (ya > y) != (yb > y):
                    交点.append(xa + (y - ya) * (xb - xa) / (yb - ya))
        if not 交点:
            continue
        交点.sort()
        for i in range(0, len(交点) - 1, 2):
            左, 右 = 交点[i], 交点[i + 1]
            for 列 in range(math.ceil(左 / 步长 - 0.5), math.floor(右 / 步长 - 0.5) + 1):
                在内.add((列, 行))
    return 在内


def 取参照点(内点数=1200, 外点数=1200):
    """参照点：中国境内一批点（必须落在底图的"陆地"里）+ 边界外一圈的点（必须落在"海"里）。

    为什么用"面"而不是只用"海岸线"：这张官方标准地图上**着色的是中国领土**，
    邻国与海洋都是白的。也就是说，着色区的边界是**国界**（大部分是陆地国界），
    不是海岸线。所以拿海岸线去配是配不上的；正确做法是拿"中国的形状"去配。

    返回 (内点们, 外点们, 栅格统计)。
    """
    环们 = 取中国环们()
    步 = 参照步长
    在内 = 栅格化(环们, 步)
    if not 在内:
        raise RuntimeError("栅格化后境内一个格子都没有 —— 数据或步长有问题")
    框内 = {(列, 行) for 列, 行 in 在内
           if 图框[0] <= 列 * 步 <= 图框[2] and 图框[1] <= 行 * 步 <= 图框[3]}
    外圈 = set()
    半宽 = int(round(1.6 / 步))
    for 列, 行 in list(框内):
        for 偏行 in range(-半宽, 半宽 + 1):
            for 偏列 in range(-半宽, 半宽 + 1):
                邻 = (列 + 偏列, 行 + 偏行)
                if 邻 in 在内:
                    continue
                if not (图框[0] <= 邻[0] * 步 <= 图框[2] and 图框[1] <= 邻[1] * 步 <= 图框[3]):
                    continue
                外圈.add(邻)

    def 抽稀(集合, 要几个):
        排序 = sorted(集合)
        步抽 = max(1, len(排序) // 要几个)
        return [(列 * 步, 行 * 步) for 列, 行 in 排序[::步抽]][:要几个]

    内点们 = 抽稀(框内, 内点数)
    外点们 = 抽稀(外圈, 外点数)
    print(f"参照点：境内 {len(框内)} 格 → 取 {len(内点们)} 点；"
          f"境外 1.6° 缓冲带 {len(外圈)} 格 → 取 {len(外点们)} 点")
    return 内点们, 外点们, {"境内格": len(框内), "境外格": len(外圈), "步长": 步}


