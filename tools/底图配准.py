def 读PNG块们(路径):
    """拆出 PNG 的各个块，返回 (信息字典, 压缩后的像素数据, 调色板)。"""
    with open(路径, "rb") as 文件:
        原始 = 文件.read()
    if 原始[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError("这不是 PNG 文件（文件头不对）")
    位置, 信息, 数据段, 调色板 = 8, {}, [], None
    while 位置 + 8 <= len(原始):
        长度, = struct.unpack(">I", 原始[位置:位置 + 4])
        类型 = 原始[位置 + 4:位置 + 8].decode("ascii", "replace")
        内容 = 原始[位置 + 8:位置 + 8 + 长度]
        位置 += 12 + 长度                       # 长度 + 类型 + 数据 + CRC
        if 类型 == "IHDR":
            宽, 高, 位深, 颜色类型, _, _, 隔行 = struct.unpack(">IIBBBBB", 内容)
            信息 = {"宽": 宽, "高": 高, "位深": 位深, "颜色类型": 颜色类型, "隔行": 隔行}
        elif 类型 == "PLTE":
            调色板 = 内容
        elif 类型 == "IDAT":
            数据段.append(内容)
        elif 类型 == "IEND":
            break
    if not 信息:
        raise ValueError("PNG 里没有 IHDR 块")
    if 信息["隔行"] != 0:
        raise ValueError("暂不支持隔行（Adam7）PNG —— 请另存为普通 PNG")
    if 信息["位深"] != 8:
        raise ValueError(f"暂不支持 {信息['位深']} 位深的 PNG —— 请另存为 8 位/通道")
    return 信息, b"".join(数据段), 调色板


def 通道数(颜色类型):
    return {0: 1, 2: 3, 3: 1, 4: 2, 6: 4}[颜色类型]


def _帕斯滤波(左, 上, 左上):
    p = 左 + 上 - 左上
    差左, 差上, 差左上 = abs(p - 左), abs(p - 上), abs(p - 左上)
    if 差左 <= 差上 and 差左 <= 差左上:
        return 左
    return 上 if 差上 <= 差左上 else 左上


def 判定颜色(r, g, b):
    """把一个像素判成「陆(1) / 海(0) / 其他(255)」。

    【这张官方图的实际配色】——用 `--重新解码 --取样` 打出调色板、再取若干点实测得到：
      · 海洋与图廓外的留白都是**近纯白** #fffffe（合起来占 59%）
      · 陆地是按省分的淡色块：#fdd2e2 淡粉、#ffe4c4 米黄、#deedd5 淡绿、
        #fffddb 淡黄、#dcd9ea / #b8a7cb 淡紫（青海、西藏一带）……
      · 海岸线与注记是深色细线；内陆湖泊是较饱和的青色

    所以判据不是"蓝=海"，而是：
      · 近纯白（几乎无彩、且很亮）→ 海（同时也是图廓外留白，两者在本图里无法区分，
        但对配准没有影响：我们要的是"海陆交界"，而图廓线是深色、不会产生假的交界）
      · 灰/黑（几乎无彩但暗）→ 其他（线划、文字：不参与拟合，免得把墨迹当海岸）
      · 其余有色像素 → 陆。注意淡紫的省区也会被判成陆（这是对的），
        而内陆湖泊被判成陆也无害 —— 我们拟合的是外海海岸线，湖在陆地内部不产生跨界。
    """
    最亮, 最暗 = max(r, g, b), min(r, g, b)
    彩度 = 最亮 - 最暗
    if 彩度 <= 8 and 最暗 >= 240:
        return 0                      # 近纯白：海 / 图廓外
    if 彩度 <= 12 and 最亮 < 240:
        return 255                    # 灰黑：线划与文字
    return 1                          # 其余有色：陆


def 解码掩膜(路径, 步长=掩膜步长):
    """解码 PNG 并降采样成「陆=1 / 海=0 / 其他=255」的小掩膜。

    返回 (宽, 高, 小宽, 小高, 掩膜 bytearray, 其它占比)。掩膜按行优先，v 轴向下。
    """
    信息, 压缩数据, 调色板 = 读PNG块们(路径)
    宽, 高, 类型 = 信息["宽"], 信息["高"], 信息["颜色类型"]
    每像素字节 = 通道数(类型)
    行字节 = 宽 * 每像素字节
    原始 = zlib.decompress(压缩数据)
    if len(原始) < (行字节 + 1) * 高:
        raise ValueError("PNG 像素数据少于预期（文件可能损坏）")

    小宽, 小高 = (宽 + 步长 - 1) // 步长, (高 + 步长 - 1) // 步长
    掩膜 = bytearray(b"\xff" * (小宽 * 小高))
    上格统计 = bytearray(小宽 * 小高 * 3)      # 每个小格内 陆/海/其他 的计数（用于多数表决）
    色统计 = {}
    位置, 上一行 = 0, bytearray(行字节)
    for y in range(高):
        滤波类型 = 原始[位置]
        行 = bytearray(原始[位置 + 1:位置 + 1 + 行字节])
        位置 += 1 + 行字节
        # ── 反滤波 ──
        if 滤波类型 == 0:
            pass
        elif 滤波类型 == 1:
            for i in range(每像素字节, 行字节):
                行[i] = (行[i] + 行[i - 每像素字节]) & 0xFF
        elif 滤波类型 == 2:
            for i in range(行字节):
                行[i] = (行[i] + 上一行[i]) & 0xFF
        elif 滤波类型 == 3:
            for i in range(行字节):
                左 = 行[i - 每像素字节] if i >= 每像素字节 else 0
                行[i] = (行[i] + ((左 + 上一行[i]) >> 1)) & 0xFF
        elif 滤波类型 == 4:
            for i in range(行字节):
                左 = 行[i - 每像素字节] if i >= 每像素字节 else 0
                左上 = 上一行[i - 每像素字节] if i >= 每像素字节 else 0
                行[i] = (行[i] + _帕斯滤波(左, 上一行[i], 左上)) & 0xFF
        else:
            raise ValueError(f"第 {y} 行的滤波类型 {滤波类型} 非法")
        上一行 = 行

        if y % 步长:                       # 只对小格的起始行做取样（一行一次，够用且快）
            continue
        小v = y // 步长
        if 小v >= 小高:
            break
        for 小u in range(小宽):
            x = 小u * 步长
            if x >= 宽:
                break
            i = x * 每像素字节
            if 类型 in (0, 4):
                r = g = b = 行[i]
            elif 类型 in (2, 6):
                r, g, b = 行[i], 行[i + 1], 行[i + 2]
            else:
                索引 = 行[i] * 3
                r, g, b = 调色板[索引], 调色板[索引 + 1], 调色板[索引 + 2]
            格 = 小v * 小宽 + 小u
            基 = 格 * 3
            类别 = 判定颜色(r, g, b)
            量化 = (r >> 4) << 8 | (g >> 4) << 4 | (b >> 4)
            色统计[量化] = 色统计.get(量化, 0) + 1
            if 类别 == 255:
                上格统计[基 + 2] += 1          # 深色/空白 → 说不上是陆是海
            elif 类别 == 0:
                上格统计[基 + 1] += 1          # 偏蓝 → 海
            else:
                上格统计[基] += 1              # 其余 → 陆
        if 小v % 200 == 0:
            print(f"    解码中… 第 {y}/{高} 行", end="\r")
    print(" " * 40, end="\r")

    # ── 多数表决 ──
    其他数 = 0
    for 格 in range(小宽 * 小高):
        基 = 格 * 3
        陆, 海, 其他 = 上格统计[基], 上格统计[基 + 1], 上格统计[基 + 2]
        if 陆 == 0 and 海 == 0:
            掩膜[格] = 255
            其他数 += 1
        elif 陆 >= 海:
            掩膜[格] = 1
        else:
            掩膜[格] = 0
    return 宽, 高, 小宽, 小高, 掩膜, 其他数 / (小宽 * 小高), 色统计


def 打印调色板(色统计, 上限=20):
    """打印出现最多的颜色（量化到 16 级/通道），用来核对"陆/海判据"是否站得住。"""
    排序 = sorted(色统计.items(), key=lambda 项: -项[1])
    总 = sum(色统计.values()) or 1
    print(f"出现最多的 {上限} 种颜色（按 16 级/通道 量化）：")
    for 量化, 次数 in 排序[:上限]:
        r = (量化 >> 8) << 4 | 8
        g = ((量化 >> 4) & 0xF) << 4 | 8
        b = (量化 & 0xF) << 4 | 8
        print(f"  #{r:02x}{g:02x}{b:02x}  B−R={b - r:+4d}  {次数 / 总:6.2%}  判为 {判定颜色(r, g, b)}")


def 取掩膜(路径=默认底图, 重新解码=False):
    """带缓存的掩膜。缓存放在临时目录（不进仓库：它是中间产物，随时可重算）。"""
    if not 重新解码 and os.path.isfile(掩膜缓存) and os.path.isfile(掩膜元信息):
        with open(掩膜元信息, encoding="utf-8") as 文件:
            元 = json.load(文件)
        if 元.get("图像") == os.path.abspath(路径) and 元.get("步长") == 掩膜步长:
            with open(掩膜缓存, "rb") as 文件:
                掩膜 = bytearray(文件.read())
            if len(掩膜) == 元["小宽"] * 元["小高"]:
                print(f"掩膜取自缓存：{元['小宽']}×{元['小高']}（步长 {掩膜步长}）")
                return 元, 掩膜
    print(f"解码底图（约需十几秒，只此一次）：{os.path.relpath(路径, 根目录)}")
    宽, 高, 小宽, 小高, 掩膜, 其它占比, 色统计 = 解码掩膜(路径)
    元 = {"图像": os.path.abspath(路径), "宽": 宽, "高": 高,
         "小宽": 小宽, "小高": 小高, "步长": 掩膜步长, "其它占比": round(其它占比, 4)}
    打印调色板(色统计)
    with open(掩膜缓存, "wb") as 文件:
        文件.write(bytes(掩膜))
    with open(掩膜元信息, "w", encoding="utf-8") as 文件:
        json.dump(元, 文件, ensure_ascii=False, indent=1)
    print(f"  解码完成：{宽}×{高} → 掩膜 {小宽}×{小高}，深色/无法判定占 {其它占比:.1%}")
    return 元, 掩膜


# ══════════════════════════════════════════════════════════════════
#  二、掩膜上的距离场（Chamfer 两遍扫描）
# ══════════════════════════════════════════════════════════════════
def 算距离场(元, 掩膜, 目标值):
    """每个格子到「最近的值为目标值(1 陆 / 0 海)的格子」的距离（单位：格×5 的整数）。"""
    小宽, 小高 = 元["小宽"], 元["小高"]
    大数 = 1 << 20
    距离 = [0 if 格 == 目标值 else 大数 for 格 in 掩膜]

    def 取(格):
        return 距离[格]

    for v in range(小高):
        基 = v * 小宽
        for u in range(小宽):
            格 = 基 + u
            if 距离[格] == 0:
                continue
            最 = 距离[格]
            if v > 0:
                最 = min(最, 取(格 - 小宽) + 5)
                if u > 0:
                    最 = min(最, 取(格 - 小宽 - 1) + 7)
                if u + 1 < 小宽:
                    最 = min(最, 取(格 - 小宽 + 1) + 7)
            if u > 0:
                最 = min(最, 取(格 - 1) + 5)
            距离[格] = 最
    for v in range(小高 - 1, -1, -1):
        基 = v * 小宽
        for u in range(小宽 - 1, -1, -1):
            格 = 基 + u
            if 距离[格] == 0:
                continue
            最 = 距离[格]
            if v + 1 < 小高:
                最 = min(最, 取(格 + 小宽) + 5)
                if u > 0:
                    最 = min(最, 取(格 + 小宽 - 1) + 7)
                if u + 1 < 小宽:
                    最 = min(最, 取(格 + 小宽 + 1) + 7)
            if u + 1 < 小宽:
                最 = min(最, 取(格 + 1) + 5)
            距离[格] = 最
    return 距离


