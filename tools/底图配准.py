# -*- coding: utf-8 -*-
"""底图自动配准：把官方标准地图的**像素位置**与**经纬度**对上（纯标准库）。

═══════════════════════════════════════════════════════════════════
【为什么需要这一步】
底图是一张位图。游戏要知道"图上第 (u, v) 个像素是哪个经纬度"，才能把州郡界叠上去。
这个换算关系（配准）没法凭想象写出来 —— 猜错几十公里，图看上去**仍然"挺像那么回事"**，
是最难发现的一类错。所以本工具用程序把它算出来，并**如实报告残差**。

【怎么算】
1. 解码 PNG（标准库 zlib + 逐行反滤波），按颜色分出「陆地 / 海洋 / 其他（文字、线划、注记）」，
   再按步长降采样成一张小掩膜。解码一次后缓存到临时目录，之后调试几秒就能跑完。
2. 取 Natural Earth 50m 海岸线（公有领域）作**参照地理数据**，抽成若干采样点。
   > 特意不用 config/map.json 里那 89 点中国轮廓：那是本项目自己概括画的，
   > 拿它去拟合官方底图等于"自己对着自己"，会把我自己画的误差一起固化进配准结果里。
3. 在掩膜上算出「每个格子到最近海陆交界处的距离」（Chamfer 两遍扫描）。
4. 把参照海岸线的采样点按候选变换投影到图上，最小化「点到最近交界处的距离」的**截尾均值**
   （截尾是为了不被少量离群点带偏，例如图上被注记盖住的地方）。
   自由参数：圆锥常数 n、缩放 s、旋转 ρ、平移 (tx, ty)。用降步长坐标下降法，**完全确定性、无随机**。
5. 写出 config/底图配准.json；`--叠加图` 可另生成一张叠加预览 PNG 供人工核验。

【依赖】仅标准库。联网只用于下载参照海岸线（有本地缓存）。
"""
