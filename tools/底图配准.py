def 圆锥XY(经度, 纬度, 圆锥常数, 中央经线):
    """兰勃特等角圆锥的「原始」坐标：x 向东、y 向北（未缩放、未平移）。"""
    极角 = 圆锥常数 * math.radians(经度 - 中央经线)
    半径 = math.tan(math.pi / 4 + math.radians(纬度) / 2) ** (-圆锥常数)
    return (半径 * math.sin(极角), 半径 * math.cos(极角))


def 投影到像素(参数, 经度, 纬度):
    """候选变换：(经度, 纬度) → 图像像素 (u, v)。

    注意符号：圆锥原始坐标的 y 是"离顶点的距离"（南边更大），图像 v 轴向下也是南边更大，
    所以 v 用 **正号**；写成负号会把整幅图上下颠倒（中国会跑到图外去）。
    """
    圆锥常数, 缩放, 旋转, 平移x, 平移y, 中央经线 = 参数
    x, y = 圆锥XY(经度, 纬度, 圆锥常数, 中央经线)
    余 = math.cos(旋转)
    正 = math.sin(旋转)
    return (缩放 * (x * 余 - y * 正) + 平移x,
            缩放 * (x * 正 + y * 余) + 平移y)


def 打分(参数, 内点们, 外点们, 距陆, 距海, 掩膜, 元):
    """平均误差（单位：图像像素）。

    内点（中国境内）应落在底图的"陆地（着色区）"里，落到海里就罚"到最近陆地的距离"。
    外点（国界外一圈）应落在底图的"海/白"里，落到着色区里就罚"到最近海的距离"。
    落在"无法判定"格（灰黑线划、注记）上的点直接跳过 —— 不拿不确定的东西凑数。
    """
    步长 = 元["步长"]
    小宽, 小高 = 元["小宽"], 元["小高"]
    总罚 = 0.0
    有效 = 0
    for 点们, 期望, 罚场 in ((内点们, 1, 距陆), (外点们, 0, 距海)):
        for 经度, 纬度 in 点们:
            u, v = 投影到像素(参数, 经度, 纬度)
            小u, 小v = int(u / 步长), int(v / 步长)
            if not (0 <= 小u < 小宽 and 0 <= 小v < 小高):
                总罚 += 60.0 / 步长        # 投到图外：按"很远"计罚（60 像素）
                有效 += 1
                continue
            格 = 小v * 小宽 + 小u
            if 掩膜[格] == 255:
                continue                  # 判不了，跳过
            有效 += 1
            if 掩膜[格] != 期望:
                总罚 += 罚场[格] / 5.0 * 步长
    return (总罚 / 有效) if 有效 else float("inf"), 有效


def 初值(内点们, 外点们, 元, 圆锥常数, 中央经线, 掩膜):
    """用「底图上着色区（中国领土）的外接框」对齐「参照中国的国界外接框」得到初值。

    初值不求准，只求落进正确的吸引域；后面靠坐标下降精修。
    """
    步长 = 元["步长"]
    小宽, 小高 = 元["小宽"], 元["小高"]
    左, 上, 右, 下 = 小宽, 小高, -1, -1
    for v in range(小高):
        基 = v * 小宽
        for u in range(小宽):
            if 掩膜[基 + u] == 1:
                左 = min(左, u)
                右 = max(右, u)
                上 = min(上, v)
                下 = max(下, v)
    if 右 < 0:
        raise RuntimeError("掩膜里一个陆地格都没有 —— 颜色判据可能不适用于这张图")
    框像素 = (左 * 步长, 上 * 步长, (右 + 1) * 步长, (下 + 1) * 步长)
    点们 = 内点们 + 外点们
    XY = [圆锥XY(经度, 纬度, 圆锥常数, 中央经线) for 经度, 纬度 in 点们]
    x0, x1 = min(p[0] for p in XY), max(p[0] for p in XY)
    y0, y1 = min(p[1] for p in XY), max(p[1] for p in XY)
    缩放x = (框像素[2] - 框像素[0]) / max(x1 - x0, 1e-9)
    缩放y = (框像素[3] - 框像素[1]) / max(y1 - y0, 1e-9)
    缩放 = (缩放x + 缩放y) / 2
    平移x = 框像素[0] - 缩放 * x0
    平移y = 框像素[1] - 缩放 * y0            # v 轴向下，y 最小的（最北）落在图像最上边
    return [圆锥常数, 缩放, 0.0, 平移x, 平移y, 中央经线], 框像素


def 坐标下降(初值参数, 内点们, 外点们, 距陆, 距海, 掩膜, 元, 最大轮=90, 报告=None):
    """确定性坐标下降：每轮对每个参数试 ± 步长，取最好的；无明显改善就减半步长。

    不用随机搜索也不用模拟退火 —— 同样的输入必须得到同样的结果（项目硬约束：零随机）。
    """
    参数 = list(初值参数)
    分 = 打分(参数, 内点们, 外点们, 距陆, 距海, 掩膜, 元)[0]
    步长们 = [0.0, abs(参数[1]) * 0.08, 0.05, 30.0, 30.0, 0.0]
    轮 = 0
    while 轮 < 最大轮 and max(步长们) > 1e-4 and any(步长们):
        改进 = False
        for i, 步 in enumerate(步长们):
            if 步 == 0:
                continue
            for 方向 in (1, -1):
                试 = list(参数)
                试[i] += 步 * 方向
                if i == 1 and 试[1] <= 0:
                    continue
                分试 = 打分(试, 内点们, 外点们, 距陆, 距海, 掩膜, 元)[0]
                if 分试 < 分 - 1e-9:
                    参数, 分, 改进 = 试, 分试, True
        if not 改进:
            步长们 = [s / 2 for s in 步长们]
        轮 += 1
        if 报告 and 轮 % 10 == 0:
            报告(f"    第 {轮} 轮：平均误差 {分:.2f} px")
    return 参数, 分


def 拟合(内点们, 外点们, 距陆, 距海, 掩膜, 元):
    """先用几个圆锥常数扫一遍（看形状对不对），再**按 config/投影.json 的取值**精修位置与大小。

    为什么最终必须用配置里的圆锥常数：游戏里所有经纬度都是按 config/投影.json 投影的，
    写出的六参数又是"图像像素 → 世界坐标"的直接换算。两者必须严格同一个 n，
    否则底图与州郡界会有一点点对不上（虽然小，但没有理由留着）。
    所以本工具的角色是**核对**：如果扫描发现最优 n 与配置值差得远，会明确报警。
    """
    配置n = 地图.圆锥常数
    最好的 = None
    内扫 = 内点们[::3]
    外扫 = 外点们[::3]
    候选 = sorted({0.45, 0.50, 0.55, 0.63, 0.68, 0.73, 0.80, round(配置n, 9)})
    for 圆锥常数 in 候选:
        初, _ = 初值(内点们, 外点们, 元, 圆锥常数, 地图.中央经线, 掩膜)
        参数, 分 = 坐标下降(初, 内扫, 外扫, 距陆, 距海, 掩膜, 元, 最大轮=80)
        print(f"  n={圆锥常数:.4f} → 平均误差 {分:.2f} px"
              + ("　← config/投影.json 的取值" if abs(圆锥常数 - 配置n) < 1e-9 else ""))
        if 最好的 is None or 分 < 最好的[1]:
            最好的 = (参数, 分, 圆锥常数)
    最优n = 最好的[2]
    if abs(最优n - 配置n) > 0.02:
        print(f"  ⚠ 扫描出的最优圆锥常数 {最优n:.4f} 与 config/投影.json 的 {配置n:.6f} 差得较远，"
              f"建议把配置改成 {最优n:.6f} 后重跑（否则底图与州郡界会有额外偏差）。")
    else:
        print(f"  扫描最优 n={最优n:.4f}，与 config/投影.json 的 {配置n:.6f} 一致（差 "
              f"{abs(最优n - 配置n):.4f}），说明投影参数可用。")
    # 精修从"扫描得到的最好解"出发（它已经在正确的吸引域里），
    # 而不是重新用外接框估一个初值 —— 后者会因为图例、南海诸岛插图而偏，容易滑到更差的局部解。
    参数, 分 = 最好的[0], 最好的[1]
    if abs(最优n - 配置n) > 1e-9:
        参数[0] = 配置n                    # 圆锥常数必须与 config/投影.json 完全一致
    print("用全部参照点精修…")
    参数, 分 = 坐标下降(参数, 内点们, 外点们, 距陆, 距海, 掩膜, 元, 最大轮=200,
                    报告=lambda 文本: print(文本))
    return 参数, 分


def 像素每度(参数, 纬度):
    """拟合出来的变换在该纬度处：1 纬度 ≈ 多少像素（用于把误差换算成千米）。"""
    经度 = 参数[5]
    a = 投影到像素(参数, 经度, 纬度 - 0.5)
    b = 投影到像素(参数, 经度, 纬度 + 0.5)
    return math.hypot(a[0] - b[0], a[1] - b[1])


def 命中率(参数, 内点们, 外点们, 掩膜, 元):
    """不算距离、只数"落在正确一侧"的比例（比平均距离更好懂）。"""
    步长 = 元["步长"]
    小宽, 小高 = 元["小宽"], 元["小高"]
    结果 = {}
    for 名, 点们, 期望 in (("境内点落在着色区", 内点们, 1), ("境外点落在白色区", 外点们, 0)):
        对 = 判不了 = 0
        for 经度, 纬度 in 点们:
            u, v = 投影到像素(参数, 经度, 纬度)
            小u, 小v = int(u / 步长), int(v / 步长)
            if not (0 <= 小u < 小宽 and 0 <= 小v < 小高):
                判不了 += 1
                continue
            值 = 掩膜[小v * 小宽 + 小u]
            if 值 == 255:
                判不了 += 1
            elif 值 == 期望:
                对 += 1
        总 = len(点们) - 判不了
        结果[名] = (对 / 总) if 总 else 0.0
    return 结果


def 反算图幅(参数, 元):
    """把图像四角反算成经纬度 —— 独立自检：官方中国全图的图幅应落在常识范围内。"""
    角们 = [(0.0, 0.0), (元["宽"], 0.0), (0.0, 元["高"]), (元["宽"], 元["高"])]
    经纬们 = [像素到经纬(参数, u, v) for u, v in 角们]
    return (min(p[0] for p in 经纬们), min(p[1] for p in 经纬们),
            max(p[0] for p in 经纬们), max(p[1] for p in 经纬们))


def 像素到经纬(参数, u, v):
    """图像像素 → 经纬度（拟合变换的逆运算，闭式）。"""
    圆锥常数, 缩放拟合, 旋转, 平移x, 平移y, 中央经线 = 参数
    余 = math.cos(旋转)
    正 = math.sin(旋转)
    p = (u - 平移x) / 缩放拟合
    q = (v - 平移y) / 缩放拟合
    X = p * 余 + q * 正
    Y = -p * 正 + q * 余
    极角 = math.atan2(X, Y)
    半径 = math.hypot(X, Y)
    if 半径 <= 0:
        return (中央经线, 90.0)
    return (中央经线 + math.degrees(极角) / 圆锥常数,
            math.degrees(2 * math.atan(半径 ** (-1.0 / 圆锥常数))) - 90.0)


def 像素到世界系数(参数):
    """把「图像像素 → 游戏世界坐标」写成六参数仿射（游戏侧直接套用，不必懂圆锥公式）。

    世界x = a·u + b·v + c ；世界y = d·u + e·v + f

    【推导】拟合变换是「圆锥原始坐标 → 像素」的相似变换：
        u = s·(X·cosρ − Y·sinρ) + tx
        v =  s·(X·sinρ + Y·cosρ) + ty
    反过来解出 (X, Y)，再按游戏自己的定义换算：
        世界x = 地图.缩放 · X
        世界y = 地图.缩放 · (Y − Y₀)，Y₀ 是参考纬度处的半径（投影的 y 零点）
    两步都是线性运算，合起来仍是六参数仿射，所以游戏侧只要存这 6 个数。
    """
    圆锥常数, 缩放拟合, 旋转, 平移x, 平移y, _ = 参数
    k = 地图.缩放 / 缩放拟合
    余 = math.cos(旋转)
    正 = math.sin(旋转)
    a = k * 余
    b = k * 正
    c = k * (-余 * 平移x - 正 * 平移y)
    d = -k * 正
    e = k * 余
    f = k * (正 * 平移x - 余 * 平移y)
    半径0 = math.tan(math.pi / 4 + math.radians(地图.参考纬度) / 2) ** (-圆锥常数)
    return (a, b, c, d, e, f - 地图.缩放 * 半径0)


