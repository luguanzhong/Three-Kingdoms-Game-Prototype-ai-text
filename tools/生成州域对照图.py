经度基准, 经度系数 = 73.0, 19.0
纬度基准, 纬度系数 = 54.0, 23.0


def 投影(经纬):
    """(经度, 纬度) → (x, y)"""
    经度, 纬度 = 经纬
    return ((经度 - 经度基准) * 经度系数, (纬度基准 - 纬度) * 纬度系数)


def 路径(点列, 闭合=True):
    """把经纬度点列转成 SVG path 的 d 属性。"""
    指令 = []
    for 序号, 点 in enumerate(点列):
        x, y = 投影(点)
        指令.append(f"{'M' if 序号 == 0 else 'L'}{x:.1f},{y:.1f}")
    if 闭合:
        指令.append("Z")
    return " ".join(指令)


