# -*- coding: utf-8 -*-
"""古今地名对照工具：校验 config/古今地名对照.json 并生成人可读文档。

用法：
    python tools/古今地名对照.py                # 校验 + 打印统计（提交前跑）
    python tools/古今地名对照.py 生成文档         # 生成 docs/古今地名对照.md
    python tools/古今地名对照.py 列存疑           # 只列出置信度为"存疑"的条目（复核时看这个）

为什么要有校验：
    这份数据是"州郡边界"的依据来源。若某条没有依据、或把"存疑"当"高"用，
    边界就会被画得理直气壮却没有根据。校验把这些情况拦下来。
"""
import json
import os
import sys

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
根目录 = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
数据路径 = os.path.join(根目录, "config", "古今地名对照.json")

合法州 = ("司隶", "豫州", "冀州", "兖州", "徐州", "青州", "荆州",
        "扬州", "益州", "凉州", "雍州", "并州", "幽州")
合法置信度 = ("高", "中", "存疑")
必填字段 = ("郡", "州", "治所", "治所今地", "今范围概述", "交界邻郡",
        "交界带今地", "置信度", "依据", "待核")


def 载入():
    if not os.path.isfile(数据路径):
        return None, [f"数据文件不存在：{数据路径}"]
    try:
        with open(数据路径, encoding="utf-8") as 文件:
            数据 = json.load(文件)
    except (OSError, json.JSONDecodeError) as 异常:
        return None, [f"数据文件无法解析：{异常}"]
    return 数据, []


def 校验(数据):
    错误 = []
    条目们 = 数据.get("条目")
    if not isinstance(条目们, list) or not 条目们:
        return ["缺少「条目」列表或列表为空"], []
    已见 = set()
    for 序号, 条 in enumerate(条目们, 1):
        位置 = f"第 {序号} 条（{条.get('郡', '未命名')}）"
        for 字段 in 必填字段:
            if 字段 not in 条:
                错误.append(f"{位置}：缺少字段「{字段}」")
        if 条.get("州") not in 合法州:
            错误.append(f"{位置}：州名非法「{条.get('州')}」")
        if 条.get("置信度") not in 合法置信度:
            错误.append(f"{位置}：置信度非法「{条.get('置信度')}」（应为 {'/'.join(合法置信度)}）")
        if not isinstance(条.get("依据"), list) or not 条.get("依据"):
            错误.append(f"{位置}：必须至少给出一条依据（没有依据的条目不得用于定界）")
        elif any(not str(x).strip() for x in 条["依据"]):
            错误.append(f"{位置}：依据里存在空白项")
        if not isinstance(条.get("交界邻郡"), list) or not 条.get("交界邻郡"):
            错误.append(f"{位置}：必须列出交界邻郡（边界考证的对象）")
        if not str(条.get("交界带今地", "")).strip():
            错误.append(f"{位置}：缺少「交界带今地」—— 这一列才是边界的主要参考")
        if not isinstance(条.get("待核"), list):
            错误.append(f"{位置}：`待核` 必须是列表（没有待核项就写空列表）")
        键 = 条.get("郡")
        if 键 in 已见:
            错误.append(f"{位置}：郡名重复「{键}」")
        已见.add(键)
    # 交界关系应当双向自洽（有 A 说与 B 接壤，B 也应当提到 A）——不一致只提示，不判错
    提示 = []
    索引 = {条["郡"]: set(条.get("交界邻郡") or []) for 条 in 条目们}
    for 郡名, 邻们 in 索引.items():
        for 邻 in 邻们:
            if 邻 in 索引 and 郡名 not in 索引[邻]:
                提示.append(f"「{郡名}」写了与「{邻}」接壤，但「{邻}」没写回来（单边记载）")
    return 错误, 提示


def 统计(数据):
    条目们 = data_条目(数据)
    按置信 = {}
    按州 = {}
    for 条 in 条目们:
        按置信[条["置信度"]] = 按置信.get(条["置信度"], 0) + 1
        按州[条["州"]] = 按州.get(条["州"], 0) + 1
    return 条目们, 按置信, 按州


def data_条目(数据):
    return 数据.get("条目") or []


def 打印统计(数据, 提示):
    条目们, 按置信, 按州 = 统计(数据)
    print(f"古今地名对照：共 {len(条目们)} 郡")
    print(f"  按置信度：{按置信}")
    print(f"  按州：{按州}")
    存疑 = [条 for 条 in 条目们 if 条["置信度"] == "存疑"]
    if 存疑:
        print(f"\n⚠ 存疑条目（{len(存疑)} 条，边界不得据此定稿）：")
        for 条 in 存疑:
            print(f"  · {条['郡']}（{条['州']}）：{'；'.join(条.get('待核') or ['（未写待核项）'])}")
    高待核 = [条 for 条 in 条目们 if 条["置信度"] == "高" and 条.get("待核")]
    if 高待核:
        print(f"\nℹ 置信度高、但仍列出待核项的（{len(高待核)} 条）：")
        for 条 in 高待核:
            print(f"  · {条['郡']}：{'；'.join(条['待核'])}")
    if 提示:
        print(f"\n（一致性提示 {len(提示)} 条，不影响校验结果）")
        for 项 in 提示[:8]:
            print("  · " + 项)


def 生成文档(数据):
    条目们, 按置信, 按州 = 统计(数据)
    置信摘要 = "、".join(f"{键} {值} 条" for 键, 值 in 按置信.items())
    州摘要 = "、".join(f"{键} {值} 郡" for 键, 值 in 按州.items())
    行 = ["# 古今地名对照（考据初稿）", "",
         "> **本文件由 `python tools/古今地名对照.py 生成文档` 自动生成，请勿手改**；",
         "> 要改内容请改 `config/古今地名对照.json` 后重新生成。",
         "> 分区与溯源机制见 [区域划分与溯源.md](区域划分与溯源.md)；数据来源等级见下。", "",
         "## 怎么读这份表", "",
         "- **治所今地**：郡治对应的现代行政区，是绘图的**锚点**；",
         "- **交界带今地**：接壤地带今天大致是哪些县市 —— **这才是边界线的主要参考**",
         "  （史料对\"郡界\"记载极少，但属县/聚落记载很全，所以边界靠交界带来反推）；",
         "- **置信度**：`高`（通说、可直接绘图）/ `中`（治所明确但范围有分歧）/ `存疑`（史料本身有争议，**不得**据此定稿）；",
         "- **依据等级**：史料原文 > 权威地图集 > 百科类线索（线索只作查证方向，不可单独作为定稿依据）。", "",
         "## 复核方法（给制作人）", "",
         "1. 先看下面的**存疑**条目与**待核**列 —— 这些是必须要核的；",
         "2. 核对时以谭其骧《中国历史地图集》第三册（三国·西晋）为准绳，逐郡比对；",
         "3. 核完把该条 `置信度` 提升、把 `待核` 项清空、在 `依据` 里补上你核对的来源；",
         "4. 跑 `python tools/古今地名对照.py` 确认无校验错误，再跑测试。", "",
         f"**当前进度：{len(条目们)} 郡　（{置信摘要}；{州摘要}）**", "",
         "## 总表", "",
         "| 郡 | 州 | 治所 | 治所今地 | 置信度 |",
         "| :--- | :--- | :--- | :--- | :--- |"]
    顺序 = sorted(条目们, key=lambda 条: (合法州.index(条["州"]) if 条["州"] in 合法州 else 99, 条["郡"]))
    for 条 in 顺序:
        标记 = {"高": "✅ 高", "中": "⚠️ 中", "存疑": "❌ 存疑"}[条["置信度"]]
        行.append(f"| {条['郡']} | {条['州']} | {条['治所']} | {条['治所今地']} | {标记} |")
    行 += ["", "## 逐条详情", ""]
    for 条 in 顺序:
        行 += [f"### {条['郡']}（{条['州']}）", "",
             f"- **治所**：{条['治所']} → {条['治所今地']}",
             f"- **今范围概述**：{条['今范围概述']}",
             f"- **交界邻郡**：{'、'.join(条['交界邻郡'])}",
             f"- **交界带今地**：{条['交界带今地']}",
             f"- **置信度**：{条['置信度']}",
             "- **依据**："]
        for 依 in 条["依据"]:
            行.append(f"  - {依}")
        if 条.get("待核"):
            行.append("- **待核**：")
            for 项 in 条["待核"]:
                行.append(f"  - {项}")
        else:
            行.append("- **待核**：无")
        行.append("")
    行 += ["---", "",
          "<p align=\"center\"><sub>由 tools/古今地名对照.py 生成　·　"
          "改数据请先改 config/古今地名对照.json 再重新生成</sub></p>", ""]
    输出 = os.path.join(根目录, "docs", "古今地名对照.md")
    with open(输出, "w", encoding="utf-8", newline="\n") as 文件:
        文件.write("\n".join(行))
    print(f"✓ 已生成 docs/古今地名对照.md（{len(条目们)} 郡）")


def 主函数():
    参数 = sys.argv[1] if len(sys.argv) > 1 else "校验"
    数据, 错误 = 载入()
    if 错误:
        print("✗ " + "；".join(错误))
        return 1
    错误, 提示 = 校验(数据)
    if 参数 == "列存疑":
        条目们, _, _ = 统计(数据)
        for 条 in 条目们:
            if 条["置信度"] == "存疑":
                print(f"❌ {条['郡']}（{条['州']}）→ 治所 {条['治所']}（{条['治所今地']}）")
                for 项 in 条.get("待核") or []:
                    print(f"     待核：{项}")
        return 0
    if 错误:
        print("✗ 校验未通过：")
        for 项 in 错误:
            print("   · " + 项)
        return 1
    print("✓ 校验通过：字段齐备、置信度合法、每条都有依据与交界带今地")
    打印统计(数据, 提示)
    if 参数 in ("生成文档", "文档"):
        print()
        生成文档(数据)
    return 0


if __name__ == "__main__":
    raise SystemExit(主函数())
